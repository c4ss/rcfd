const code = (s: string) => '`' + s + '`';

function shortName(c: Capability): string {
  return c.id.slice(c.id.indexOf(':') + 1);
}

/** The markdown report: counts, then today's gaps by kind and target item. Deterministic: no clock, no paths. */
