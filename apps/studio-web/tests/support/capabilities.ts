// The capability inventory of F-824: what the engine can do, read from the engine itself. (The map of the Studio's own
// coverage of it, guardrail G15's, was retired by ADR 0808, F-981, on the maintainer's answer of 2026-11-26 in ADR 0803.)
//
// Sources, all asked of the binaries at generation time, never typed in by hand:
//   service_method       `rcfd serve --stdio`, `service.info` -> `methods`
//   case_key             `rcfd serve --stdio`, `settings.schema` -> `case` (every leaf key; `*` stands for a named entry)
//   monitor_format_key   `rcfd serve --stdio`, `settings.schema` -> `monitors` (the rcfd-monitors format the plots read)
//   mcp_tool             `rcfd-mcp`, MCP `tools/list`, without and with `--project` (a scratch folder)
//   cli_command          `rcfd --help`, `rcfd-runner --help`, `rcfd-mcp --help` (the COMMANDS blocks; the server binary
//                        rcfd-mcp, which has no commands, is one command itself)
//   cli_option           every `--flag` of those help texts, under the command whose block names it
//
// The inventory file (capabilities/inventory.json) is written by `npm run capabilities` and checked against the engine
// by tests/unit/capabilities.spec.ts; docs/studio-coverage.md is the report generated from it.
//
// Only erasable TypeScript and Node built-ins: scripts/write-capabilities.mjs runs this file with type stripping.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export const KINDS = ['service_method', 'mcp_tool', 'cli_command', 'cli_option', 'case_key', 'monitor_format_key'] as const;
export type CapabilityKind = (typeof KINDS)[number];

export const KIND_TITLES: Record<CapabilityKind, string> = {
  service_method: 'Service methods',
  mcp_tool: 'MCP tools',
  cli_command: 'CLI commands',
  cli_option: 'CLI options',
  case_key: 'Case schema keys',
  monitor_format_key: 'Monitor format keys',
};

export type JsonScalar = string | number | boolean | null;

export interface Capability {
  /** Stable id: `<prefix>:<name>`, the prefix fixed per kind (service:, mcp:, cli:, case:, monitors:). */
  readonly id: string;
  readonly kind: CapabilityKind;
  /** Where the generator read it. */
  readonly source: string;
  /** cli_option: the id of its command (which need not be a capability itself, e.g. `cli:rcfd` for `--help`). */
  readonly parent?: string;
  /** cli_command: its usage as the help prints it. */
  readonly usage?: string;
  /** mcp_tool: the access class (`_meta."rcfd/access"`) in each server mode that lists it. */
  readonly access?: Readonly<Record<string, string>>;
  /** case_key, monitor_format_key: the JSON Schema type. */
  readonly type?: string | readonly string[];
  /** case_key: the allowed values (the solver options of the key), when the schema enumerates them. */
  readonly enum?: readonly JsonScalar[];
}

export interface Inventory {
  readonly format: 'rcfd-studio-capabilities';
  readonly version: 1;
  readonly note: string;
  readonly engine: Readonly<Record<string, string>>;
  readonly sources: Readonly<Record<string, string>>;
  readonly counts: Readonly<Record<string, number>>;
  readonly capabilities: readonly Capability[];
}

const ID_PREFIX: Record<CapabilityKind, string> = {
  service_method: 'service:',
  mcp_tool: 'mcp:',
  cli_command: 'cli:',
  cli_option: 'cli:',
  case_key: 'case:',
  monitor_format_key: 'monitors:',
};

export const INVENTORY_NOTE =
  'Generated by `npm run capabilities` (apps/studio-web/scripts/write-capabilities.mjs) from the rcfd binaries; never edit by hand. tests/unit/capabilities.spec.ts fails when it differs from the engine.';

export const SOURCES: Record<string, string> = {
  'service.info': 'rcfd serve --stdio; service.info, member methods',
  'settings.schema': 'rcfd serve --stdio; settings.schema, members case and monitors (leaf keys; * is a named entry)',
  'tools/list': 'rcfd-mcp (stdio) MCP tools/list, without --project and with --project <scratch project folder>',
  help: '<binary> --help of rcfd, rcfd-runner and rcfd-mcp (commands of the COMMANDS block; every --flag under the command whose block names it)',
};

// ---- Parsing what the engine prints (pure functions, unit-tested on their own) ----

type SchemaNode = { readonly [k: string]: unknown };

const isObject = (v: unknown): v is SchemaNode => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Every leaf key of a JSON Schema (as settings.schema writes it: properties, additionalProperties maps, items). */
export function schemaLeaves(schema: SchemaNode): Array<{ path: string; node: SchemaNode }> {
  const out: Array<{ path: string; node: SchemaNode }> = [];
  const walk = (node: SchemaNode, at: string[]) => {
    let inner = false;
    const props = node['properties'];
    if (isObject(props)) {
      for (const [k, v] of Object.entries(props)) {
        if (isObject(v)) {
          inner = true;
          walk(v, [...at, k]);
        }
      }
    }
    const ap = node['additionalProperties'];
    if (isObject(ap)) {
      inner = true;
      walk(ap, [...at, '*']);
    }
    const items = node['items'];
    if (isObject(items) && (isObject(items['properties']) || isObject(items['additionalProperties']))) {
      inner = true;
      walk(items, [...at, '[]']);
    }
    if (!inner && at.length > 0) out.push({ path: at.join('.'), node });
  };
  walk(schema, []);
  return out;
}

function schemaCapability(kind: 'case_key' | 'monitor_format_key', p: string, node: SchemaNode): Capability {
  const type = node['type'];
  const items = node['items'];
  const values = Array.isArray(node['enum']) ? node['enum'] : isObject(items) && Array.isArray(items['enum']) ? items['enum'] : undefined;
  return {
    id: ID_PREFIX[kind] + p,
    kind,
    source: 'settings.schema',
    ...(typeof type === 'string' || Array.isArray(type) ? { type: type as string | string[] } : {}),
    ...(values ? { enum: values as JsonScalar[] } : {}),
  };
}

/** The capabilities of a `settings.schema` reply ({case, monitors}). */
export function schemaCapabilities(reply: SchemaNode): Capability[] {
  const caseSchema = reply['case'];
  const monitors = reply['monitors'];
  if (!isObject(caseSchema) || !isObject(monitors)) throw new Error('settings.schema: the reply has no case and monitors schemas');
  return [
    ...schemaLeaves(caseSchema).map((l) => schemaCapability('case_key', l.path, l.node)),
    ...schemaLeaves(monitors).map((l) => schemaCapability('monitor_format_key', l.path, l.node)),
  ];
}

/** Splits `s` at ` | ` outside brackets ([...], <...>). */
function splitAlternatives(s: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = '';
  for (let i = 0; i < s.length; i++) {
    const c = s[i]!;
    if (c === '[' || c === '<') depth++;
    if (c === ']' || c === '>') depth = Math.max(0, depth - 1);
    if (depth === 0 && s.startsWith(' | ', i)) {
      out.push(cur.trim());
      cur = '';
      i += 2;
      continue;
    }
    cur += c;
  }
  out.push(cur.trim());
  return out.filter((a) => a.length > 0);
}

/** The command names a usage line declares: `data list|verify|provenance [...]` gives three, `cases [list]` one. */
export function commandNames(usage: string): string[] {
  const names: string[] = [];
  for (const alt of splitAlternatives(usage)) {
    const words: string[][] = [];
    for (const t of alt.split(/\s+/)) {
      if (!/^[a-z][a-z0-9-]*(\|[a-z][a-z0-9-]*)*$/.test(t)) break;
      words.push(t.split('|'));
    }
    let acc: string[] = [''];
    for (const w of words) acc = acc.flatMap((a) => w.map((x) => (a ? `${a} ${x}` : x)));
    names.push(...acc.filter((a) => a.length > 0));
  }
  return names;
}

const FLAG = /--[a-z][a-z0-9-]*/g;

/**
 * The commands and options of one binary's `--help`. A line that starts in column 0 after a blank line (or first) opens
 * a section, and further column-0 lines continue its title; inside `COMMANDS:`
 * a line indented by exactly four spaces declares commands, and every `--flag` up to the next such line is theirs. A
 * section titled `... of <cmd> and <cmd> ...` gives its flags to those commands; every other flag belongs to the binary.
 * A binary without a COMMANDS block is one command itself.
 */
export function helpCapabilities(bin: string, text: string): Capability[] {
  const root = `cli:${bin}`;
  const commands = new Map<string, Capability>();
  const options = new Map<string, Capability>();
  const addFlags = (line: string, parents: readonly string[]) => {
    for (const f of line.match(FLAG) ?? []) {
      for (const parent of parents) {
        const id = `${parent} ${f}`;
        if (!options.has(id)) options.set(id, { id, kind: 'cli_option', source: 'help', parent });
      }
    }
  };
  let section = '';
  let current: string[] = [];
  let hasCommands = false;
  let afterBlank = true;
  for (const raw of text.replace(/\r\n/g, '\n').split('\n')) {
    if (raw.trim() === '') {
      afterBlank = true;
      continue;
    }
    const opens = afterBlank && /^\S/.test(raw);
    afterBlank = false;
    if (opens) {
      section = raw.trim();
      current = [];
      const of = /\bof ([a-z][a-z0-9-]*(?:(?:, | and )[a-z][a-z0-9-]*)*)/.exec(section);
      if (of && section !== 'COMMANDS:') {
        const named = of[1]!.split(/, | and /).map((n) => `${root} ${n}`).filter((id) => commands.has(id));
        if (named.length > 0) current = named;
      }
      addFlags(section, current.length > 0 ? current : [root]);
      continue;
    }
    if (section === 'COMMANDS:' && /^ {4}[a-z]/.test(raw)) {
      hasCommands = true;
      const usage = raw.trim().split(/\s{2,}/)[0]!;
      current = commandNames(usage).map((n) => `${root} ${n}`);
      for (const id of current) if (!commands.has(id)) commands.set(id, { id, kind: 'cli_command', source: 'help', usage });
      addFlags(raw, current);
      continue;
    }
    addFlags(raw, current.length > 0 ? current : [root]);
  }
  if (!hasCommands) commands.set(root, { id: root, kind: 'cli_command', source: 'help', usage: bin });
  return [...commands.values(), ...options.values()];
}

interface McpTool {
  readonly name: string;
  readonly _meta?: { readonly [k: string]: unknown };
}

/** The tools of each server mode, merged by name; `access` keeps each mode's access class. */
export function mcpCapabilities(modes: Readonly<Record<string, readonly McpTool[]>>): Capability[] {
  const byName = new Map<string, Record<string, string>>();
  for (const [mode, tools] of Object.entries(modes)) {
    for (const t of tools) {
      const access = t._meta?.['rcfd/access'];
      const entry = byName.get(t.name) ?? {};
      entry[mode] = typeof access === 'string' ? access : 'unknown';
      byName.set(t.name, entry);
    }
  }
  return [...byName].map(([name, access]) => ({ id: `mcp:${name}`, kind: 'mcp_tool' as const, source: 'tools/list', access }));
}

export function serviceCapabilities(methods: readonly string[]): Capability[] {
  return methods.map((m) => ({ id: `service:${m}`, kind: 'service_method' as const, source: 'service.info' }));
}

const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** The inventory in its one canonical form: capabilities ordered by kind, then id; counts per kind. */
export function buildInventory(engine: Record<string, string>, caps: readonly Capability[]): Inventory {
  const seen = new Set<string>();
  for (const c of caps) {
    if (seen.has(c.id)) throw new Error(`two capabilities with the id ${c.id}`);
    seen.add(c.id);
  }
  const sorted = [...caps].sort((a, b) => KINDS.indexOf(a.kind) - KINDS.indexOf(b.kind) || cmp(a.id, b.id));
  const counts: Record<string, number> = {};
  for (const k of KINDS) counts[k] = sorted.filter((c) => c.kind === k).length;
  counts['total'] = sorted.length;
  return { format: 'rcfd-studio-capabilities', version: 1, note: INVENTORY_NOTE, engine, sources: SOURCES, counts, capabilities: sorted };
}

/** The file text: the header as indented JSON, then one capability per line (small diffs when the engine changes). */
export function inventoryText(inv: Inventory): string {
  const { capabilities, ...head } = inv;
  const top = JSON.stringify(head, null, 2);
  const lines = capabilities.map((c) => '    ' + JSON.stringify(c));
  return `${top.slice(0, -2)},\n  "capabilities": [\n${lines.join(',\n')}\n  ]\n}\n`;
}

// ---- Asking the engine ----

export interface EngineBinaries {
  readonly rcfd: string;
  readonly runner: string;
  readonly mcp: string;
}

/** rcfd-runner and rcfd-mcp next to `rcfd` (as `cargo build --release` and `cargo install` place them). */
export function engineBinaries(rcfd: string): EngineBinaries | { missing: string[] } {
  const ext = path.extname(rcfd);
  const dir = path.dirname(rcfd);
  const runner = path.join(dir, `rcfd-runner${ext}`);
  const mcp = path.join(dir, `rcfd-mcp${ext}`);
  const missing = [runner, mcp].filter((p) => !existsSync(p));
  return missing.length > 0 ? { missing } : { rcfd, runner, mcp };
}

function run(bin: string, args: readonly string[], input?: string): string {
  const r = spawnSync(bin, args, { input: input ?? '', encoding: 'utf8', timeout: 60_000, windowsHide: true, maxBuffer: 64 << 20 });
  if (r.error) throw r.error;
  if (r.status !== 0) throw new Error(`${path.basename(bin)} ${args.join(' ')} ended with ${r.status}: ${r.stderr}`);
  return r.stdout;
}

/** Sends newline-delimited JSON-RPC requests on stdin (then EOF) and returns the replies by id. */
function rpcOverStdio(bin: string, args: readonly string[], requests: readonly object[]): Map<number, SchemaNode> {
  const out = run(bin, args, requests.map((r) => JSON.stringify(r)).join('\n') + '\n');
  const replies = new Map<number, SchemaNode>();
  for (const line of out.split('\n')) {
    if (line.trim() === '') continue;
    const msg = JSON.parse(line) as SchemaNode;
    if (typeof msg['id'] !== 'number') continue;
    if (msg['error'] !== undefined) throw new Error(`${path.basename(bin)}: request ${msg['id']} failed: ${JSON.stringify(msg['error'])}`);
    replies.set(msg['id'], msg['result'] as SchemaNode);
  }
  return replies;
}

function mcpToolsList(mcp: string, args: readonly string[]): { tools: McpTool[]; init: SchemaNode } {
  const replies = rpcOverStdio(mcp, args, [
    { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'rcfd-studio-inventory', version: '1' } } },
    { jsonrpc: '2.0', method: 'notifications/initialized' },
    { jsonrpc: '2.0', id: 2, method: 'tools/list' },
  ]);
  const init = replies.get(1);
  const list = replies.get(2);
  if (!init || !list || !Array.isArray(list['tools'])) throw new Error(`rcfd-mcp ${args.join(' ')}: no tools/list reply`);
  return { tools: list['tools'] as McpTool[], init };
}

/** Asks the engine for everything it can do. Starts only short-lived processes; writes only a scratch folder it removes. */
export function readEngine(bins: EngineBinaries): Inventory {
  const replies = rpcOverStdio(bins.rcfd, ['serve', '--stdio'], [
    { jsonrpc: '2.0', id: 1, method: 'service.info' },
    { jsonrpc: '2.0', id: 2, method: 'settings.schema' },
  ]);
  const info = replies.get(1);
  const schema = replies.get(2);
  if (!info || !Array.isArray(info['methods']) || !schema) throw new Error('rcfd serve --stdio: no service.info or settings.schema reply');

  const scratch = mkdtempSync(path.join(os.tmpdir(), 'rcfd-f824-'));
  let plain: ReturnType<typeof mcpToolsList>;
  let project: ReturnType<typeof mcpToolsList>;
  try {
    writeFileSync(
      path.join(scratch, 'rcfd-project.json'),
      JSON.stringify({ schema_version: 1, name: 'capability inventory', created: '2026-11-16T00:00:00.000Z', solver_version_created: `rcfd ${String(info['version'])}` }),
    );
    plain = mcpToolsList(bins.mcp, []);
    project = mcpToolsList(bins.mcp, ['--project', scratch]);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }

  const caps = [
    ...serviceCapabilities(info['methods'] as string[]),
    ...schemaCapabilities(schema),
    ...mcpCapabilities({ default: plain.tools, project: project.tools }),
    ...helpCapabilities('rcfd', run(bins.rcfd, ['--help'])),
    ...helpCapabilities('rcfd-runner', run(bins.runner, ['--help'])),
    ...helpCapabilities('rcfd-mcp', run(bins.mcp, ['--help'])),
  ];
  const server = (plain.init['serverInfo'] ?? {}) as SchemaNode;
  return buildInventory(
    {
      rcfd: String(info['version']),
      service_protocol: String(info['protocol']),
      service_protocol_version: String(info['protocol_version']),
      mcp_server: `${String(server['name'])} ${String(server['version'])}`,
      mcp_protocol_version: String(plain.init['protocolVersion']),
    },
    caps,
  );
}

// ---- The report (docs/studio-coverage.md) ----

const code = (s: string) => '`' + s + '`';

function shortName(c: Capability): string {
  return c.id.slice(c.id.indexOf(':') + 1);
}

/** Counts of `keys` in first-seen order: `a` (2), `b` (1). */
function counted(keys: readonly string[]): string {
  const n = new Map<string, number>();
  for (const k of keys) n.set(k, (n.get(k) ?? 0) + 1);
  return [...n].map(([k, c]) => `${code(k)} (${c})`).join(', ');
}

/**
 * The markdown report of the inventory: counts by kind, then every capability by name (case keys by section, CLI options
 * by command). Deterministic: no clock, no paths. Since ADR 0808 (F-981, G15 retired by ADR 0803) it holds no map of the
 * Studio's own surfaces.
 */
export function inventoryReport(inv: Inventory): string {
  const L: string[] = [];
  const caps = inv.capabilities;
  const of = (k: CapabilityKind) => caps.filter((c) => c.kind === k);

  L.push('# Studio capability inventory', '');
  L.push(
    'This page lists what the rcfd engine can do, read from the engine itself (F-824, [ADR 0800](adr/0800-electron-studio-roadmap.md)):',
    'every service method, MCP tool, CLI command and option, case-schema key and monitor format key. Guardrail G15, which held',
    'each of them to a way in by hand, was retired on 2026-11-26 ([ADR 0803](adr/0803-the-studio-as-claudes-canvas-record.md));',
    'its map went with ADR 0808 (F-981). The Studio is the canvas Claude drives (G23 of the [Studio guardrails](studio-guardrails.md)),',
    'and every capability is reached through the engine\'s own interfaces (G16).',
    '',
  );
  L.push(
    'The page is generated; do not edit it. `npm run capabilities` in `apps/studio-web` asks the binaries (`rcfd serve --stdio`',
    'for `service.info` and `settings.schema`, `rcfd-mcp` for its MCP `tools/list` with and without `--project`, and the',
    '`--help` of `rcfd`, `rcfd-runner` and `rcfd-mcp`), writes `apps/studio-web/capabilities/inventory.json`, and writes this',
    'page from it. The Studio\'s unit tests (`tests/unit/capabilities.spec.ts`, run by `npm test`) fail when this page is not',
    'the generated one and when the inventory differs from the engine (that last check is skipped, with the reason, when no',
    '`rcfd` binary is found).',
    '',
  );
  const eng = inv.engine;
  L.push(
    `Engine read: rcfd ${eng['rcfd']}, service protocol ${eng['service_protocol']} version ${eng['service_protocol_version']}, MCP server ${eng['mcp_server']}` +
      ` (MCP protocol ${eng['mcp_protocol_version']}).`,
    '',
  );

  L.push('## Summary', '');
  L.push('| Kind | Capabilities |', '|---|---|');
  for (const k of KINDS) L.push(`| ${KIND_TITLES[k]} | ${of(k).length} |`);
  L.push(`| **All** | **${caps.length}** |`, '');
  L.push(
    'A case key stands for every value of its enumeration (the solver options of that key, listed in the inventory). A CLI',
    'option is listed under its command.',
    '',
  );

  for (const k of KINDS) {
    const list = of(k);
    L.push(`## ${KIND_TITLES[k]} (${list.length})`, '');
    if (list.length === 0) {
      L.push('None.', '');
      continue;
    }
    if (k === 'case_key') L.push(`By section: ${counted(list.map((c) => shortName(c).split('.')[0]!))}.`, '');
    else if (k === 'cli_option') L.push(`By command: ${counted(list.map((c) => c.parent!.slice(4)))}.`, '');
    else L.push(`${list.map((c) => code(shortName(c))).join(', ')}.`, '');
  }

  L.push('## What the inventory leaves out', '');
  L.push(
    '- The bulk data methods `data.*` (protocol 1.2, ADR 0350): they exist only in a service that an embedding program',
    '  switches on, and `rcfd serve` does not, so `service.info` does not list them. F-804 is their Studio item.',
    '- The co-simulation participants that `rcfd serve --cosim <case>` hosts: the `cosim.*` methods are listed, the',
    '  participants depend on a case.',
    '- `rcfd-studio` and `rcfd-gui`: removed on 2026-11-16 (G14, F-449); they were not engine capabilities.',
    '- The arguments of each MCP tool and service method (their input schemas): the tool or method is the capability.',
    '- Exit codes, event kinds of `events.poll` and error codes: the engine prints or documents them but has no list to read.',
    '',
  );

  L.push('## Engine-side gaps (proposals under G4)', '');
  L.push(
    'G4 lets the engine grow only by addition. None of these is needed for the inventory to be complete today; each would',
    'make it less fragile, and each needs its own ADR and the maintainer before any Rust changes:',
    '',
    '1. A machine-readable command list. `rcfd <command> --help` prints the whole help, not the command\'s, and no command',
    '   prints the list as data, so the generator parses the help text by its layout (a four-space indent opens a command).',
    '   Proposal: a new `rcfd help --json` (and the same in `rcfd-runner` and `rcfd-mcp`) that prints every command with its',
    '   usage and options; the help text stays byte for byte.',
    '2. Opt-in method groups. `service.info` lists only the methods that are on. Proposal: an additive member (for example',
    '   `optional_methods`) naming the groups an embedding program can switch on (`data.*`), so the inventory can list them.',
    '3. The project-mode tool list. `rcfd-mcp` lists its project tools only when started on a project folder, so the',
    '   generator writes a scratch `rcfd-project.json`. Proposal: `rcfd-mcp --list-tools [--project]` printing `tools/list`',
    '   with no folder.',
    '',
  );

  L.push('## Where to go next', '');
  L.push(
    '- [Studio guardrails](studio-guardrails.md): G16 and G23.',
    '- [Service protocol](service-protocol.md), [MCP tools](mcp-tools.md) and [case schema](case-schema.md): what each capability does.',
  );
  return L.join('\n') + '\n';
}
