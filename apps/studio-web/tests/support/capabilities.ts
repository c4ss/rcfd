  const unplanned = exempt.filter((c) => res.resolved.get(c.id)!.exemption!.unplanned === true);
  const pct = (n: number) => `${((100 * n) / Math.max(1, caps.length)).toFixed(1)} %`;

  L.push('# Studio capability coverage', '');
