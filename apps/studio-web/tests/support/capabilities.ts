// ---- Parsing what the engine prints (pure functions, unit-tested on their own) ----

type SchemaNode = { readonly [k: string]: unknown };

const isObject = (v: unknown): v is SchemaNode => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Every leaf key of a JSON Schema (as settings.schema writes it: properties, additionalProperties maps, items). */
export function schemaLeaves(schema: SchemaNode): Array<{ path: string; node: SchemaNode }> {
  const out: Array<{ path: string; node: SchemaNode }> = [];
  const walk = (node: SchemaNode, at: string[]) => {
    let inner = false;
    const props = node['properties'];
    if (isObject(props)) {
      for (const [k, v] of Object.entries(props)) {
        if (isObject(v)) {
          inner = true;
          walk(v, [...at, k]);
        }
      }
    }
    const ap = node['additionalProperties'];
    if (isObject(ap)) {
      inner = true;
      walk(ap, [...at, '*']);
    }
    const items = node['items'];
    if (isObject(items) && (isObject(items['properties']) || isObject(items['additionalProperties']))) {
      inner = true;
      walk(items, [...at, '[]']);
    }
    if (!inner && at.length > 0) out.push({ path: at.join('.'), node });
  };
  walk(schema, []);
  return out;
}

function schemaCapability(kind: 'case_key' | 'monitor_format_key', p: string, node: SchemaNode): Capability {
  const type = node['type'];
  const items = node['items'];
  const values = Array.isArray(node['enum']) ? node['enum'] : isObject(items) && Array.isArray(items['enum']) ? items['enum'] : undefined;
  return {
    id: ID_PREFIX[kind] + p,
    kind,
    source: 'settings.schema',
    ...(typeof type === 'string' || Array.isArray(type) ? { type: type as string | string[] } : {}),
    ...(values ? { enum: values as JsonScalar[] } : {}),
  };
}

/** The capabilities of a `settings.schema` reply ({case, monitors}). */
export function schemaCapabilities(reply: SchemaNode): Capability[] {
  const caseSchema = reply['case'];
  const monitors = reply['monitors'];
  if (!isObject(caseSchema) || !isObject(monitors)) throw new Error('settings.schema: the reply has no case and monitors schemas');
  return [
    ...schemaLeaves(caseSchema).map((l) => schemaCapability('case_key', l.path, l.node)),
    ...schemaLeaves(monitors).map((l) => schemaCapability('monitor_format_key', l.path, l.node)),
  ];
}

/** Splits `s` at ` | ` outside brackets ([...], <...>). */
function splitAlternatives(s: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = '';
  for (let i = 0; i < s.length; i++) {
    const c = s[i]!;
    if (c === '[' || c === '<') depth++;
    if (c === ']' || c === '>') depth = Math.max(0, depth - 1);
    if (depth === 0 && s.startsWith(' | ', i)) {
      out.push(cur.trim());
      cur = '';
      i += 2;
      continue;
    }
    cur += c;
  }
  out.push(cur.trim());
  return out.filter((a) => a.length > 0);
}

/** The command names a usage line declares: `data list|verify|provenance [...]` gives three, `cases [list]` one. */
export function commandNames(usage: string): string[] {
  const names: string[] = [];
  for (const alt of splitAlternatives(usage)) {
    const words: string[][] = [];
    for (const t of alt.split(/\s+/)) {
      if (!/^[a-z][a-z0-9-]*(\|[a-z][a-z0-9-]*)*$/.test(t)) break;
      words.push(t.split('|'));
    }
    let acc: string[] = [''];
    for (const w of words) acc = acc.flatMap((a) => w.map((x) => (a ? `${a} ${x}` : x)));
    names.push(...acc.filter((a) => a.length > 0));
  }
  return names;
}

const FLAG = /--[a-z][a-z0-9-]*/g;

/**
 * The commands and options of one binary's `--help`. A line that starts in column 0 after a blank line (or first) opens
 * a section, and further column-0 lines continue its title; inside `COMMANDS:`
 * a line indented by exactly four spaces declares commands, and every `--flag` up to the next such line is theirs. A
 * section titled `... of <cmd> and <cmd> ...` gives its flags to those commands; every other flag belongs to the binary.
 * A binary without a COMMANDS block is one command itself.
 */
export function helpCapabilities(bin: string, text: string): Capability[] {
  const root = `cli:${bin}`;
  const commands = new Map<string, Capability>();
  const options = new Map<string, Capability>();
  const addFlags = (line: string, parents: readonly string[]) => {
    for (const f of line.match(FLAG) ?? []) {
      for (const parent of parents) {
        const id = `${parent} ${f}`;
        if (!options.has(id)) options.set(id, { id, kind: 'cli_option', source: 'help', parent });
      }
    }
  };
  let section = '';
  let current: string[] = [];
  let hasCommands = false;
  let afterBlank = true;
  for (const raw of text.replace(/\r\n/g, '\n').split('\n')) {
    if (raw.trim() === '') {
      afterBlank = true;
      continue;
    }
    const opens = afterBlank && /^\S/.test(raw);
    afterBlank = false;
    if (opens) {
      section = raw.trim();
      current = [];
      const of = /\bof ([a-z][a-z0-9-]*(?:(?:, | and )[a-z][a-z0-9-]*)*)/.exec(section);
      if (of && section !== 'COMMANDS:') {
        const named = of[1]!.split(/, | and /).map((n) => `${root} ${n}`).filter((id) => commands.has(id));
        if (named.length > 0) current = named;
      }
      addFlags(section, current.length > 0 ? current : [root]);
      continue;
    }
    if (section === 'COMMANDS:' && /^ {4}[a-z]/.test(raw)) {
      hasCommands = true;
      const usage = raw.trim().split(/\s{2,}/)[0]!;
      current = commandNames(usage).map((n) => `${root} ${n}`);
      for (const id of current) if (!commands.has(id)) commands.set(id, { id, kind: 'cli_command', source: 'help', usage });
      addFlags(raw, current);
      continue;
    }
    addFlags(raw, current.length > 0 ? current : [root]);
  }
  if (!hasCommands) commands.set(root, { id: root, kind: 'cli_command', source: 'help', usage: bin });
  return [...commands.values(), ...options.values()];
}

interface McpTool {
  readonly name: string;
  readonly _meta?: { readonly [k: string]: unknown };
}

/** The tools of each server mode, merged by name; `access` keeps each mode's access class. */
export function mcpCapabilities(modes: Readonly<Record<string, readonly McpTool[]>>): Capability[] {
  const byName = new Map<string, Record<string, string>>();
  for (const [mode, tools] of Object.entries(modes)) {
    for (const t of tools) {
      const access = t._meta?.['rcfd/access'];
      const entry = byName.get(t.name) ?? {};
      entry[mode] = typeof access === 'string' ? access : 'unknown';
      byName.set(t.name, entry);
    }
  }
  return [...byName].map(([name, access]) => ({ id: `mcp:${name}`, kind: 'mcp_tool' as const, source: 'tools/list', access }));
}

export function serviceCapabilities(methods: readonly string[]): Capability[] {
  return methods.map((m) => ({ id: `service:${m}`, kind: 'service_method' as const, source: 'service.info' }));
}

const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** The inventory in its one canonical form: capabilities ordered by kind, then id; counts per kind. */
export function buildInventory(engine: Record<string, string>, caps: readonly Capability[]): Inventory {
  const seen = new Set<string>();
  for (const c of caps) {
    if (seen.has(c.id)) throw new Error(`two capabilities with the id ${c.id}`);
    seen.add(c.id);
  }
  const sorted = [...caps].sort((a, b) => KINDS.indexOf(a.kind) - KINDS.indexOf(b.kind) || cmp(a.id, b.id));
  const counts: Record<string, number> = {};
  for (const k of KINDS) counts[k] = sorted.filter((c) => c.kind === k).length;
  counts['total'] = sorted.length;
  return { format: 'rcfd-studio-capabilities', version: 1, note: INVENTORY_NOTE, engine, sources: SOURCES, counts, capabilities: sorted };
}

/** The file text: the header as indented JSON, then one capability per line (small diffs when the engine changes). */
export function inventoryText(inv: Inventory): string {
  const { capabilities, ...head } = inv;
  const top = JSON.stringify(head, null, 2);
  const lines = capabilities.map((c) => '    ' + JSON.stringify(c));
  return `${top.slice(0, -2)},\n  "capabilities": [\n${lines.join(',\n')}\n  ]\n}\n`;
}

// ---- Asking the engine ----

export interface EngineBinaries {
  readonly rcfd: string;
  readonly runner: string;
  readonly mcp: string;
}

/** rcfd-runner and rcfd-mcp next to `rcfd` (as `cargo build --release` and `cargo install` place them). */
export function engineBinaries(rcfd: string): EngineBinaries | { missing: string[] } {
  const ext = path.extname(rcfd);
  const dir = path.dirname(rcfd);
  const runner = path.join(dir, `rcfd-runner${ext}`);
  const mcp = path.join(dir, `rcfd-mcp${ext}`);
  const missing = [runner, mcp].filter((p) => !existsSync(p));
  return missing.length > 0 ? { missing } : { rcfd, runner, mcp };
}

function run(bin: string, args: readonly string[], input?: string): string {
  const r = spawnSync(bin, args, { input: input ?? '', encoding: 'utf8', timeout: 60_000, windowsHide: true, maxBuffer: 64 << 20 });
  if (r.error) throw r.error;
  if (r.status !== 0) throw new Error(`${path.basename(bin)} ${args.join(' ')} ended with ${r.status}: ${r.stderr}`);
  return r.stdout;
}

/** Sends newline-delimited JSON-RPC requests on stdin (then EOF) and returns the replies by id. */
function rpcOverStdio(bin: string, args: readonly string[], requests: readonly object[]): Map<number, SchemaNode> {
  const out = run(bin, args, requests.map((r) => JSON.stringify(r)).join('\n') + '\n');
  const replies = new Map<number, SchemaNode>();
  for (const line of out.split('\n')) {
    if (line.trim() === '') continue;
    const msg = JSON.parse(line) as SchemaNode;
    if (typeof msg['id'] !== 'number') continue;
    if (msg['error'] !== undefined) throw new Error(`${path.basename(bin)}: request ${msg['id']} failed: ${JSON.stringify(msg['error'])}`);
    replies.set(msg['id'], msg['result'] as SchemaNode);
  }
  return replies;
}

function mcpToolsList(mcp: string, args: readonly string[]): { tools: McpTool[]; init: SchemaNode } {
  const replies = rpcOverStdio(mcp, args, [
    { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'rcfd-studio-inventory', version: '1' } } },
    { jsonrpc: '2.0', method: 'notifications/initialized' },
    { jsonrpc: '2.0', id: 2, method: 'tools/list' },
  ]);
  const init = replies.get(1);
  const list = replies.get(2);
  if (!init || !list || !Array.isArray(list['tools'])) throw new Error(`rcfd-mcp ${args.join(' ')}: no tools/list reply`);
  return { tools: list['tools'] as McpTool[], init };
}

/** Asks the engine for everything it can do. Starts only short-lived processes; writes only a scratch folder it removes. */
export function readEngine(bins: EngineBinaries): Inventory {
  const replies = rpcOverStdio(bins.rcfd, ['serve', '--stdio'], [
    { jsonrpc: '2.0', id: 1, method: 'service.info' },
    { jsonrpc: '2.0', id: 2, method: 'settings.schema' },
  ]);
  const info = replies.get(1);
  const schema = replies.get(2);
  if (!info || !Array.isArray(info['methods']) || !schema) throw new Error('rcfd serve --stdio: no service.info or settings.schema reply');

  const scratch = mkdtempSync(path.join(os.tmpdir(), 'rcfd-f824-'));
  let plain: ReturnType<typeof mcpToolsList>;
  let project: ReturnType<typeof mcpToolsList>;
  try {
    writeFileSync(
      path.join(scratch, 'rcfd-project.json'),
      JSON.stringify({ schema_version: 1, name: 'capability inventory', created: '2026-11-16T00:00:00.000Z', solver_version_created: `rcfd ${String(info['version'])}` }),
    );
    plain = mcpToolsList(bins.mcp, []);
    project = mcpToolsList(bins.mcp, ['--project', scratch]);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }

  const caps = [
    ...serviceCapabilities(info['methods'] as string[]),
    ...schemaCapabilities(schema),
    ...mcpCapabilities({ default: plain.tools, project: project.tools }),
    ...helpCapabilities('rcfd', run(bins.rcfd, ['--help'])),
    ...helpCapabilities('rcfd-runner', run(bins.runner, ['--help'])),
    ...helpCapabilities('rcfd-mcp', run(bins.mcp, ['--help'])),
  ];
  const server = (plain.init['serverInfo'] ?? {}) as SchemaNode;
  return buildInventory(
    {
      rcfd: String(info['version']),
      service_protocol: String(info['protocol']),
      service_protocol_version: String(info['protocol_version']),
      mcp_server: `${String(server['name'])} ${String(server['version'])}`,
      mcp_protocol_version: String(plain.init['protocolVersion']),
    },
    caps,
  );
}

// ---- Coverage: the hand-kept map from capability to UI path or exemption ----

export interface Exemption {
  /** Why there is no UI path yet. */
  readonly reason: string;
  /** When the exemption was recorded (YYYY-MM-DD). */
  readonly date: string;
  /** The roadmap item expected to give it a UI path (docs/roadmap.json). */
  readonly item: string;
  /** True when that item's acceptance does not name the capability: the item is its nearest home, not a plan. */
  readonly unplanned?: boolean;
}

export interface CoverageRule {
  /** One capability, by id. */
  readonly id?: string;
  /**
   * The members of one parent: a top-level case section (`case:<section>.`) or a CLI command's options
   * (`cli:<binary>[ <command>] --`). Never a whole kind, and never service methods or MCP tools, which are mapped one by one.
   */
  readonly prefix?: string;
  /** Where the Studio reaches it, in words (later: the action of the F-827 registry). */
  readonly ui?: string;
  readonly exemption?: Exemption;
}

export interface CoverageFile {
  readonly format: 'rcfd-studio-coverage';
  readonly version: 1;
  readonly note: string;
  readonly rules: readonly CoverageRule[];
}

export interface RoadmapItem {
  readonly id: string;
  readonly title: string;
}

export interface CoverageResult {
  /** capability id -> the rule that maps it */
  readonly resolved: ReadonlyMap<string, CoverageRule>;
  /** Capabilities no rule maps: each one fails the test. */
  readonly unmapped: readonly string[];
  /** Rules that are malformed, name an unknown item, or map nothing (a removed capability): each one fails the test. */
  readonly problems: readonly string[];
}

const PREFIX_FORMS = [/^case:[a-z0-9_]+\.$/, /^cli:[a-z][a-z0-9-]*( [a-z][a-z0-9-]*)* --$/];

function validDate(s: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  const d = new Date(`${s}T00:00:00Z`);
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === s;
}

export function checkCoverage(inv: Inventory, cov: CoverageFile, roadmap: readonly RoadmapItem[]): CoverageResult {
  const problems: string[] = [];
  const items = new Set(roadmap.map((r) => r.id));
  const byId = new Map<string, CoverageRule>();
  const prefixes: CoverageRule[] = [];
  const where = (r: CoverageRule) => r.id ?? r.prefix ?? JSON.stringify(r);
  if (cov.format !== 'rcfd-studio-coverage' || cov.version !== 1) problems.push('coverage file: format must be rcfd-studio-coverage, version 1');
  for (const r of cov.rules) {
    const w = where(r);
    if ((r.id === undefined) === (r.prefix === undefined)) problems.push(`${w}: a rule has exactly one of id and prefix`);
    if ((r.ui === undefined) === (r.exemption === undefined)) problems.push(`${w}: a rule has exactly one of ui and exemption`);
    if (r.ui !== undefined && r.ui.trim() === '') problems.push(`${w}: ui is empty`);
    if (r.exemption) {
      const e = r.exemption;
      if (typeof e.reason !== 'string' || e.reason.trim() === '') problems.push(`${w}: the exemption has no reason`);
      if (typeof e.date !== 'string' || !validDate(e.date)) problems.push(`${w}: the exemption's date is not a YYYY-MM-DD date`);
      if (typeof e.item !== 'string' || !items.has(e.item)) problems.push(`${w}: the exemption's item ${String(e.item)} is not in docs/roadmap.json`);
      if (e.unplanned !== undefined && typeof e.unplanned !== 'boolean') problems.push(`${w}: unplanned is true or absent`);
    }
    if (r.id !== undefined) {
      if (byId.has(r.id)) problems.push(`${w}: mapped twice`);
      byId.set(r.id, r);
    }
    if (r.prefix !== undefined) {
      if (!PREFIX_FORMS.some((f) => f.test(r.prefix!))) problems.push(`${w}: a prefix names one case section (case:<section>.) or one command's options (cli:<command> --)`);
      if (prefixes.some((p) => p.prefix === r.prefix)) problems.push(`${w}: mapped twice`);
      prefixes.push(r);
    }
  }
  prefixes.sort((a, b) => b.prefix!.length - a.prefix!.length);
  const resolved = new Map<string, CoverageRule>();
  const used = new Set<CoverageRule>();
  const unmapped: string[] = [];
  for (const c of inv.capabilities) {
    const rule = byId.get(c.id) ?? prefixes.find((p) => c.id.startsWith(p.prefix!));
    if (rule) {
      resolved.set(c.id, rule);
      used.add(rule);
    } else {
      unmapped.push(c.id);
    }
  }
  for (const r of cov.rules) if (!used.has(r)) problems.push(`${where(r)}: maps no capability of the inventory (removed from the engine? then remove the rule)`);
  return { resolved, unmapped, problems };
}

