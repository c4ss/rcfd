#!/usr/bin/env python3
"""Generate/refresh entities/roadmap-<area>.md from docs/roadmap.json + scripts/roadmap_progress.py.

Run from the repo root (or a snapshot worktree root): python wiki/tools/gen_roadmap_pages.py [commit-label]

Inputs (docs/roadmap.json, scripts/roadmap_progress.py, docs/adr/ file names) are read from the
current directory, or from RCFD_INPUT_DIR if set (e.g. a `git archive` export of origin/main, so a
snapshot wiki can catch up without checking anything out). Pages are written to this script's wiki.

Only the block between GEN_BEGIN and GEN_END is rewritten; everything else on the page (hand-written
synthesis, links, contradictions) is preserved. A new page gets a skeleton around the block.
"""
import ast
import datetime as dt
import json
import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(os.environ.get("RCFD_INPUT_DIR") or Path.cwd())
WIKI = Path(__file__).resolve().parent.parent
LABEL = sys.argv[1] if len(sys.argv) > 1 else "working tree"
GEN_BEGIN = "<!-- generated by tools/gen_roadmap_pages.py: begin (do not edit inside) -->"
GEN_END = "<!-- generated by tools/gen_roadmap_pages.py: end -->"
TODAY = dt.date.today().isoformat()
HUB_MIN_ADRS = 5


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def categories():
    tree = ast.parse((REPO / "scripts/roadmap_progress.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "CATEGORIES" for t in node.targets):
            return ast.literal_eval(node.value)
    sys.exit("CATEGORIES not found")


def adr_counts():
    c = defaultdict(list)
    for p in (REPO / "docs/adr").glob("[0-9][0-9][0-9][0-9]-f[0-9]*"):
        m = re.match(r"(\d{4})-f(\d+)", p.name)
        if m:
            c[int(m.group(2))].append(m.group(1))
    return c


def cell(s):
    s = (s or "").replace("|", "\\|").replace("\n", " ").strip()
    return s.replace("[[", "\\[\\[").replace("]]", "\\]\\]")  # roadmap text is not a wikilink


def main():
    data = json.loads((REPO / "docs/roadmap.json").read_text(encoding="utf-8"))
    items = data["items"] if isinstance(data, dict) and "items" in data else data
    by_id = {int(i["id"][2:]): i for i in items}
    adrs = adr_counts()
    out_pages = []
    for family, name, ids in categories():
        page = WIKI / "entities" / f"roadmap-{slug(name)}.md"
        rows = [by_id[n] for n in sorted(ids) if n in by_id]
        st = Counter(i["status"] for i in rows)
        hubs = sorted((n for n in ids if len(adrs.get(n, [])) >= HUB_MIN_ADRS), key=lambda n: -len(adrs[n]))
        g = [GEN_BEGIN, "",
             f"Generated from `docs/roadmap.json` and `scripts/roadmap_progress.py` at {LABEL} on {TODAY}.", "",
             f"**{len(rows)} items:** {st.get('done', 0)} done, {st.get('partial', 0)} partial, {st.get('todo', 0)} not started.", ""]
        if hubs:
            g += ["**Hub items** (5+ ADRs name them in their file name): " +
                  ", ".join(f"F-{n:03d} ({len(adrs[n])} ADRs)" for n in hubs), ""]
        g += ["| Item | Title | Status | ADRs | Milestones | Gap (what is missing now) |", "|---|---|---|---|---|---|"]
        for i in rows:
            n = int(i["id"][2:])
            a = adrs.get(n, [])
            a_txt = ", ".join(a) if len(a) <= 4 else f"{', '.join(a[:3])} … (+{len(a) - 3})"
            g.append(f"| {i['id']} | {cell(i['title'])} | {i['status']} | {a_txt} | {cell(', '.join(i.get('milestones') or []))} | {cell(i.get('gap')) if i['status'] != 'done' else ''} |")
        g += ["", GEN_END]
        block = "\n".join(g)
        if page.exists():
            text = page.read_text(encoding="utf-8")
            if GEN_BEGIN in text and GEN_END in text:
                pre, rest = text.split(GEN_BEGIN, 1)
                _, post = rest.split(GEN_END, 1)
                text = pre + block + post
                text = re.sub(r"^updated: .*$", f"updated: {TODAY}", text, count=1, flags=re.M)
            else:
                text = text.rstrip() + "\n\n" + block + "\n"
        else:
            text = "\n".join([
                "---", "type: entity", "tags: [roadmap, area]", "sources: [doc-roadmap-json, doc-roadmap-overview]",
                f"created: {TODAY}", f"updated: {TODAY}", "status: draft", "---", "",
                f"# Roadmap area: {name}", "",
                f"**What it is:** the '{name}' line of work ({family} family) of the [[roadmap]], with every [[f-item]] in it ([[doc-roadmap-json]]).",
                "**Where:** `docs/roadmap.json` (source of truth), categories in `scripts/roadmap_progress.py`.", "",
                "## Synthesis", "", "_Current state of this line of work, written from the ADR threads (P3)._", "",
                "## ADR threads", "", "_Thread pages in `sources/adr-thread-*` that cover this area (P3)._", "",
                "## Items", "", block, "",
            ])
        page.write_text(text, encoding="utf-8")
        out_pages.append((page.stem, name, len(rows), st))
    for stem, name, n, st in out_pages:
        print(f"{stem}\t{name}\t{n}\t{st.get('done', 0)}/{st.get('partial', 0)}/{st.get('todo', 0)}")


if __name__ == "__main__":
    main()
