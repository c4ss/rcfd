"""Collect the gap lists of all ingest jobs into a tracked page.

Each ingest job writes `.handoff/<job>.md` (gitignored). Its `## Not ingested` and
`## Contradictions` sections are the wiki's list of known gaps: sources that could not be
read, nodes left out, conflicts between sources. This script copies them, verbatim and
grouped by job, into `analyses/open-gaps.md` between generated markers, so they survive a
cleanup of `.handoff/` and show up in the index, the graph and lint.

Text outside the markers is kept, so the page can carry hand-written notes (e.g. a gap
closed by a later ingest). Run from `wiki/`:  python tools/build_gaps.py
"""
import re
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from unwrap import unwrap  # handoff text may be hard-wrapped; the wiki rule is one line per paragraph

ROOT = Path(__file__).resolve().parent.parent
HANDOFF = ROOT / ".handoff"
PAGE = ROOT / "analyses" / "open-gaps.md"
BEGIN = "<!-- generated by tools/build_gaps.py: begin (do not edit inside) -->"
END = "<!-- generated by tools/build_gaps.py: end -->"
SECTIONS = {"not ingested": "Not ingested", "contradictions": "Contradictions"}
EMPTY = re.compile(r"^\s*(-\s*)?(none|n/a|0|no contradictions?\.?|nothing)\b", re.I)


def sections(text):
    """Return {canonical name: body} for the wanted `## ` sections of a handoff."""
    out = {}
    parts = re.split(r"^## +(.+?)\s*$", text, flags=re.M)
    for head, body in zip(parts[1::2], parts[2::2]):
        key = head.strip().lower()
        for want, name in SECTIONS.items():
            if key.startswith(want):
                body = body.strip()
                if body and not EMPTY.match(body):
                    out[name] = body
    return out


def generated():
    jobs = []
    for h in sorted(HANDOFF.glob("*.md")):
        found = sections(h.read_text(encoding="utf-8"))
        if found:
            jobs.append((h.stem, found))
    lines = [BEGIN, ""]
    n_gap = sum(1 for _, f in jobs if "Not ingested" in f)
    n_con = sum(1 for _, f in jobs if "Contradictions" in f)
    lines.append(f"Copied from `.handoff/*.md` on {date.today().isoformat()}: {len(jobs)} jobs, "
                 f"{n_gap} with gaps, {n_con} with contradictions. Text is the job's own, unedited.")
    lines.append("")
    for job, found in jobs:
        lines.append(f"### {job}")
        lines.append("")
        for name in ("Not ingested", "Contradictions"):
            if name in found:
                lines.append(f"**{name}**")
                lines.append("")
                lines.append(found[name])
                lines.append("")
    lines.append(END)
    return "\n".join(lines)


def skeleton():
    today = date.today().isoformat()
    return f"""---
type: analysis
tags: [gaps, lint, sources-wanted]
sources: []
created: {today}
updated: {today}
status: draft
---

# Open gaps

What the ingest jobs could not cover: nodes or sections left out because no readable source was found, sources that could not be read (licence, paywall, certificate, 403), and conflicts between sources. This is the wiki's list of sources wanted and questions to ask, the "data gaps" step of lint. See also [[ingest-plan]] and [[foundations-sources]].

## How to use

- To close a gap: find a readable open source, ingest it, then note the closure below the generated block (the block itself is regenerated from the handoffs).
- Gaps that need a maintainer decision go to the maintainer, not into a page as if decided.

## Closed or answered

*(hand-written; none yet)*

## By job

{BEGIN}
{END}
"""


def main():
    text = PAGE.read_text(encoding="utf-8") if PAGE.exists() else skeleton()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{PAGE} has no generated markers; not touching it")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    new = unwrap(pre + generated() + post)
    new = re.sub(r"^updated: .*$", f"updated: {date.today().isoformat()}", new, count=1, flags=re.M)
    PAGE.write_text(new, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
