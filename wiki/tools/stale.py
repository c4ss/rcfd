"""Find wiki pages made stale by changes in the repo since they were ingested.

Every repo-derived source page records where it came from:
- `origin: docs/<file>.md` and `origin_commit: <sha>` in the frontmatter, and for a section
  page, `section "<heading>"` on its **Origin:** line;
- ADR thread pages (`origin: docs/adr/ (ADR list below)`) link each ADR file.
This script compares those files (or just that section) between `origin_commit` and a target
ref (default `origin/main`) and reports:
1. source pages whose origin changed (with a line count of the change);
2. pages that cite a changed source page in their `sources:` (review these next);
3. ADR files added since the snapshot that no thread page links yet (ingest backlog);
4. whether `docs/roadmap.json` changed (rerun tools/gen_roadmap_pages.py).

Staleness by provenance, not by age. Read-only on the repo (git show / git diff only).
Run from `wiki/`:  python tools/stale.py [--to origin/main] [--write]
--write puts the report into analyses/stale-report.md between generated markers.
"""
import argparse
import re
import subprocess
from collections import defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
PAGE = ROOT / "analyses" / "stale-report.md"
BEGIN = "<!-- generated by tools/stale.py: begin (do not edit inside) -->"
END = "<!-- generated by tools/stale.py: end -->"
ADR_LINK = re.compile(r"\]\((?:\.\./)+docs/adr/([^)#\s]+\.md)")
# the heading may itself contain quotes: take up to the quote followed by `,`, ` (` or ` at`
SECTION = re.compile(r'section "(.+?)"(?=\s*(?:,|\(|at\b|$))')


def git(*args):
    r = subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    return r.stdout if r.returncode == 0 else None


def show(rev, path):
    out = git("show", f"{rev}:{path}")
    if out is None:
        return None
    # ignore CRLF and trailing-space differences
    return "\n".join(line.rstrip() for line in out.splitlines())


def frontmatter(text):
    if not text.startswith("---"):
        return {}
    block = text.split("---", 2)[1]
    fm = {}
    for line in block.splitlines():
        m = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if m:
            fm[m.group(1)] = m.group(2).strip()
    return fm


def list_field(text, key):
    """`sources:` as a flow list or a block list."""
    if not text.startswith("---"):
        return []
    block = text.split("---", 2)[1]
    m = re.search(rf"^{key}:\s*\[(.*?)\]", block, re.M)
    if m:
        return [x.strip() for x in m.group(1).split(",") if x.strip()]
    m = re.search(rf"^{key}:\s*\n((?:\s+-\s+.*\n?)+)", block, re.M)
    if m:
        return [x.strip()[2:].strip() for x in m.group(1).splitlines() if x.strip().startswith("-")]
    return []


def norm(s):
    return re.sub(r"[`*_]", "", s).strip().lower()


def section_text(doc, heading):
    """Text of the section whose heading matches `heading`, up to the next heading of the same or higher level."""
    if doc is None:
        return None
    lines = doc.splitlines()
    want = norm(heading)
    heads = [(i, re.match(r"^(#+)\s+(.*)$", line)) for i, line in enumerate(lines)]
    heads = [(i, m) for i, m in heads if m]
    # exact title first; else the recorded name is the heading without its trailing "(F-..., ADR ...)"
    exact = [(i, m) for i, m in heads if norm(m.group(2)) == want]
    prefix = [(i, m) for i, m in heads if norm(m.group(2)).startswith(want)]
    pick = exact or (prefix if len(prefix) == 1 else [])
    if not pick:
        return None
    i, m = pick[0]
    level = len(m.group(1))
    out = [lines[i]]
    for nxt in lines[i + 1:]:
        n = re.match(r"^(#+)\s", nxt)
        if n and len(n.group(1)) <= level:
            break
        out.append(nxt)
    return "\n".join(out).strip()  # a following section added below leaves only blank-line noise


def changed_lines(a, b):
    if a == b:
        return 0
    sa, sb = a.splitlines(), b.splitlines()
    import difflib
    return sum(1 for d in difflib.unified_diff(sa, sb, lineterm="", n=0)
               if d[:1] in "+-" and not d.startswith(("+++", "---")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--to", default="origin/main")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    target = git("rev-parse", "--short", args.to)
    if not target:
        raise SystemExit(f"cannot resolve {args.to}")
    target = target.strip()

    stale = []          # (page, origin, detail)
    unknown = []        # (page, reason)
    linked_adrs = set()
    split_docs = set()
    snapshots = set()
    for p in sorted((ROOT / "sources").glob("*.md")):
        text = p.read_text(encoding="utf-8")
        fm = frontmatter(text)
        origin, base = fm.get("origin", ""), fm.get("origin_commit", "")
        if not base or origin.startswith("http"):
            continue
        snapshots.add(base)
        if origin.startswith("docs/adr/"):
            files = sorted(set(ADR_LINK.findall(text)))
            linked_adrs.update(files)
            moved = []
            for f in files:
                old, new = show(base, f"docs/adr/{f}"), show(args.to, f"docs/adr/{f}")
                if old is None:
                    continue
                if new is None:
                    moved.append(f"{f} (removed or renamed)")
                elif old != new:
                    moved.append(f"{f} ({changed_lines(old, new)} lines)")
            if moved:
                stale.append((p.stem, "ADR thread", "; ".join(moved)))
            continue
        path = origin.split()[0].rstrip("/")
        old, new = show(base, path), show(args.to, path)
        if old is None and new is None:
            # a directory origin: compare the tree listing
            d = git("diff", "--stat", base, args.to, "--", path)
            if d and d.strip():
                stale.append((p.stem, path, d.strip().splitlines()[-1].strip()))
            continue
        m = SECTION.search(text)
        if m:
            split_docs.add((path, base))
            so, sn = section_text(old, m.group(1)), section_text(new, m.group(1))
            if so is None:
                unknown.append((p.stem, f'section "{m.group(1)}" not found at {base}'))
                continue
            if sn is None:
                stale.append((p.stem, path, f'section "{m.group(1)}" removed or renamed'))
            elif so != sn:
                stale.append((p.stem, path, f"section changed, {changed_lines(so, sn)} lines"))
        elif old != new:
            stale.append((p.stem, path, f"file changed, {changed_lines(old or '', new or '')} lines"))

    # split docs (one page per section): headings added since the snapshot have no page yet
    new_sections = []
    for path, base in sorted(split_docs):
        old, new = show(base, path), show(args.to, path)
        if old is None or new is None:
            continue
        hs = lambda d: [m.group(2).strip() for m in re.finditer(r"^(##)\s+(.*)$", d, re.M)]
        known = {norm(h) for h in hs(old)}
        new_sections += [(path, h) for h in hs(new) if norm(h) not in known]

    stale_names = {s[0] for s in stale}
    dependents = defaultdict(list)
    for d in ("entities", "concepts", "analyses"):
        for p in sorted((ROOT / d).glob("*.md")):
            hit = [s for s in list_field(p.read_text(encoding="utf-8"), "sources") if s in stale_names]
            if hit:
                dependents[p.stem] = hit

    new_adrs = []
    for base in sorted(snapshots):
        added = git("diff", "--name-only", "--diff-filter=A", base, args.to, "--", "docs/adr/")
        for f in (added or "").splitlines():
            name = f[len("docs/adr/"):]
            if "/" not in name and name.endswith(".md") and re.match(r"\d{4}-", name) and name not in linked_adrs:
                new_adrs.append(name)
    new_adrs = sorted(set(new_adrs))
    roadmap = any(git("diff", "--quiet", b, args.to, "--", "docs/roadmap.json") is None for b in snapshots)

    out = [f"Compared each page's `origin_commit` ({', '.join(sorted(snapshots))}) with `{args.to}` ({target}) on {date.today().isoformat()}.", ""]
    out.append(f"## Source pages whose origin changed ({len(stale)})")
    out.append("")
    out += [f"- [[{n}]]: `{o}`: {d}" for n, o, d in stale] or ["- none"]
    out += ["", f"## Pages citing a changed source ({len(dependents)})", ""]
    out += [f"- [[{n}]] cites {', '.join(f'[[{s}]]' for s in hits)}" for n, hits in sorted(dependents.items())] or ["- none"]
    out += ["", f"## New sections in split docs, no page yet ({len(new_sections)})", ""]
    out += [f"- `{p}`: {h}" for p, h in new_sections] or ["- none"]
    out += ["", f"## New ADRs not yet in a thread page ({len(new_adrs)})", ""]
    out += [f"- [{f}](../../docs/adr/{f})" for f in new_adrs] or ["- none"]
    out += ["", "## Roadmap", ""]
    out.append("- `docs/roadmap.json` changed: rerun `python wiki/tools/gen_roadmap_pages.py` from the repo root." if roadmap
               else "- `docs/roadmap.json` unchanged.")
    if unknown:
        out += ["", f"## Could not check ({len(unknown)})", ""]
        out += [f"- [[{n}]]: {r}" for n, r in unknown]
    report = "\n".join(out)

    if not args.write:
        print(report)
        return
    if PAGE.exists():
        text = PAGE.read_text(encoding="utf-8")
    else:
        today = date.today().isoformat()
        text = f"""---
type: analysis
tags: [lint, staleness]
sources: []
created: {today}
updated: {today}
status: draft
---

# Stale report

Which wiki pages the repo has moved past since they were ingested, found by comparing each source page's recorded origin with the current repo (see `tools/stale.py`). Work through it as the ingest backlog: re-read the changed source, update the source page and set its `origin_commit`, then review the pages that cite it. See [[ingest-plan]] and [[open-gaps]].

{BEGIN}
{END}
"""
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    text = pre + BEGIN + "\n\n" + report + "\n\n" + END + post
    text = re.sub(r"^updated: .*$", f"updated: {date.today().isoformat()}", text, count=1, flags=re.M)
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}: {len(stale)} stale sources, {len(dependents)} dependents, {len(new_adrs)} new ADRs")


if __name__ == "__main__":
    main()
