"""Local hybrid search and relatedness for the wiki (keyword BM25 + Ollama embeddings).

The index.md catalog stops scaling at a few hundred pages; this adds search without a service.
Pages are split into sections (chunks), each chunk is embedded with a local Ollama model, and
the vectors are cached in `.handoff/embeddings.json` (gitignored, rebuilt on demand; only
changed chunks are re-embedded). Nothing leaves the machine.

Commands (run from `wiki/`):
  python tools/search.py index                    embed new/changed pages
  python tools/search.py search "query" [-k 10]   hybrid search (BM25 + vector, reciprocal-rank fusion)
  python tools/search.py similar <page> [-k 10]   pages nearest to a page, marking which are linked
  python tools/search.py report                   write analyses/related-candidates.md (lint input):
                                                  missing links, possible duplicates, similar pages with no shared source

Environment: OLLAMA_HOST (default http://localhost:11434), WIKI_EMBED_MODEL (default qwen3-embedding:0.6b).
"""
import argparse
import hashlib
import json
import math
import os
import re
import sys
import urllib.request
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / ".handoff" / "embeddings.json"
REPORT = ROOT / "analyses" / "related-candidates.md"
# 127.0.0.1, not localhost: on Windows, Python tries IPv6 ::1 first and Ollama listens on IPv4 only,
# which cost ~21 s per request (measured 2026-11-22: 21.1 s vs 0.06 s).
HOST = os.environ.get("OLLAMA_HOST", "http://127.0.0.1:11434").rstrip("/")
if not HOST.startswith("http"):
    HOST = "http://" + HOST  # OLLAMA_HOST is often set as host:port for the server itself
HOST = HOST.replace("//localhost", "//127.0.0.1").replace("//0.0.0.0", "//127.0.0.1")
KEEP_ALIVE = os.environ.get("WIKI_EMBED_KEEP_ALIVE", "30m")  # keep the model loaded between queries
MODEL = os.environ.get("WIKI_EMBED_MODEL", "qwen3-embedding:0.6b")
DIRS = ["sources", "entities", "concepts", "analyses"]
TOP = ["overview.md", "ingest-plan.md"]
SKIP = {"related-candidates", "stale-report", "open-gaps"}  # generated reports would match everything
CHUNK_CHARS = 2400
QUERY_PREFIX = "Instruct: Given a question about a CFD code and its documentation, retrieve the wiki pages that answer it\nQuery: "
LINK = re.compile(r"\[\[([^\]|#^]+)(?:[#^][^\]|]*)?(?:\|[^\]]*)?\]\]")
BEGIN = "<!-- generated by tools/search.py: begin (do not edit inside) -->"
END = "<!-- generated by tools/search.py: end -->"


# ---------- pages and chunks ----------

def pages():
    files = [ROOT / t for t in TOP if (ROOT / t).exists()]
    for d in DIRS:
        files += sorted((ROOT / d).glob("*.md"))
    return [f for f in files if f.stem not in SKIP]


def split_page(text):
    """(frontmatter dict-ish text, title, body)."""
    fm = ""
    if text.startswith("---"):
        _, fm, text = text.split("---", 2)
    m = re.search(r"^#\s+(.+)$", text, re.M)
    title = m.group(1).strip() if m else ""
    return fm, title, text


def fm_list(fm, key):
    m = re.search(rf"^{key}:\s*\[(.*?)\]", fm, re.M)
    if m:
        return [x.strip() for x in m.group(1).split(",") if x.strip()]
    m = re.search(rf"^{key}:\s*\n((?:\s+-\s+.*\n?)+)", fm, re.M)
    if m:
        return [x.strip()[2:].strip() for x in m.group(1).splitlines() if x.strip().startswith("-")]
    return []


def chunks(name, title, body):
    """Split at `## ` headings, then by size; every chunk is prefixed with the page title."""
    parts = re.split(r"(?=^## )", body, flags=re.M)
    out = []
    for part in parts:
        part = part.strip()
        while part:
            piece, part = part[:CHUNK_CHARS], part[CHUNK_CHARS:]
            if piece.strip():
                out.append(f"{title or name}\n\n{piece}")
    return out or [title or name]


def load_pages():
    data = {}
    for p in pages():
        text = p.read_text(encoding="utf-8")
        fm, title, body = split_page(text)
        data[p.stem] = {
            "path": p.relative_to(ROOT).as_posix(),
            "title": title,
            "body": body,
            "sources": fm_list(fm, "sources"),
            "builds_on": fm_list(fm, "builds_on"),
            "links": set(LINK.findall(body)),
            "type": (re.search(r"^type:\s*(\S+)", fm, re.M) or [None, ""])[1],
            "chunks": chunks(p.stem, title, body),
        }
    return data


# ---------- embeddings ----------

def embed(texts):
    out = []
    for i in range(0, len(texts), 32):
        req = urllib.request.Request(f"{HOST}/api/embed", method="POST",
                                     data=json.dumps({"model": MODEL, "input": texts[i:i + 32], "keep_alive": KEEP_ALIVE}).encode(),
                                     headers={"Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=600) as r:
                out += json.load(r)["embeddings"]
        except OSError as e:
            raise SystemExit(f"Ollama not reachable at {HOST} ({e}). Start it, or set OLLAMA_HOST.")
    return [normalise(v) for v in out]


def normalise(v):
    n = math.sqrt(sum(x * x for x in v)) or 1.0
    return [x / n for x in v]


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def h(s):
    return hashlib.sha1(s.encode("utf-8")).hexdigest()[:16]


def load_cache():
    if CACHE.exists():
        c = json.loads(CACHE.read_text(encoding="utf-8"))
        if c.get("model") == MODEL:
            return c
    return {"model": MODEL, "chunks": {}}


def index(data, quiet=False):
    cache = load_cache()
    want = {h(c): c for page in data.values() for c in page["chunks"]}
    todo = [k for k in want if k not in cache["chunks"]]
    CACHE.parent.mkdir(exist_ok=True)
    if todo and not quiet:
        print(f"embedding {len(todo)} new or changed chunks with {MODEL} ...", file=sys.stderr)
    step = 256  # save after each step, so an interrupted run keeps its work
    for i in range(0, len(todo), step):
        part = todo[i:i + step]
        vecs = embed([want[k] for k in part])
        cache["chunks"].update({k: [round(x, 6) for x in v] for k, v in zip(part, vecs)})
        CACHE.write_text(json.dumps(cache), encoding="utf-8")
        if not quiet:
            print(f"  {min(i + step, len(todo))}/{len(todo)}", file=sys.stderr, flush=True)
    before = len(cache["chunks"])
    cache["chunks"] = {k: v for k, v in cache["chunks"].items() if k in want}  # drop stale
    if todo or len(cache["chunks"]) != before:  # don't rewrite 45 MB when nothing changed
        CACHE.write_text(json.dumps(cache), encoding="utf-8")
    for page in data.values():
        page["vecs"] = [cache["chunks"][h(c)] for c in page["chunks"]]
        mean = [sum(col) / len(page["vecs"]) for col in zip(*page["vecs"])]
        page["vec"] = normalise(mean)
    if not quiet:
        print(f"{len(data)} pages, {len(want)} chunks indexed ({len(todo)} embedded now)", file=sys.stderr)
    return data


# ---------- keyword (BM25) ----------

TOKEN = re.compile(r"[a-z0-9][a-z0-9+\-]*")


def tokens(s):
    return TOKEN.findall(s.lower())


def bm25(data, query, k1=1.2, b=0.75):
    docs = {n: Counter(tokens(p["title"] + " " + p["title"] + " " + p["body"])) for n, p in data.items()}
    avg = sum(sum(c.values()) for c in docs.values()) / max(len(docs), 1)
    df = Counter(t for c in docs.values() for t in c)
    N = len(docs)
    scores = {}
    for n, c in docs.items():
        L = sum(c.values())
        s = 0.0
        for t in set(tokens(query)):
            if t in c:
                idf = math.log(1 + (N - df[t] + 0.5) / (df[t] + 0.5))
                s += idf * c[t] * (k1 + 1) / (c[t] + k1 * (1 - b + b * L / avg))
        if s > 0:
            scores[n] = s
    return scores


def rrf(*rankings, k=60):
    fused = defaultdict(float)
    for ranking in rankings:
        for r, name in enumerate(ranking):
            fused[name] += 1.0 / (k + r + 1)
    return sorted(fused, key=fused.get, reverse=True)


# ---------- commands ----------

def summary(data, name):
    """The page's index.md line if there is one, else its title."""
    idx = (ROOT / "index.md").read_text(encoding="utf-8")
    m = re.search(rf"^- \[\[{re.escape(name)}\]\] — (.*)$", idx, re.M)
    return (m.group(1) if m else data[name]["title"])[:160]


def cmd_search(data, query, k):
    q = embed([QUERY_PREFIX + query])[0]
    vec = {n: max(dot(q, v) for v in p["vecs"]) for n, p in data.items()}
    kw = bm25(data, query)
    by_vec = sorted(vec, key=vec.get, reverse=True)[:100]
    by_kw = sorted(kw, key=kw.get, reverse=True)[:100]
    for name in rrf(by_vec, by_kw)[:k]:
        print(f"[[{name}]]  vec {vec[name]:.3f}  kw {kw.get(name, 0):.1f}  — {summary(data, name)}")


def linked(data, a, b):
    return b in data[a]["links"] or a in data[b]["links"] or b in data[a]["sources"] or a in data[b]["sources"]


def cmd_similar(data, name, k):
    if name not in data:
        raise SystemExit(f"no page {name}")
    v = data[name]["vec"]
    near = sorted((n for n in data if n != name), key=lambda n: dot(v, data[n]["vec"]), reverse=True)[:k]
    for n in near:
        mark = "linked" if linked(data, name, n) else "NOT LINKED"
        print(f"{dot(v, data[n]['vec']):.3f}  {mark:10}  [[{n}]] — {summary(data, n)}")


def pairs(data, names):
    names = sorted(names)
    out = []
    for i, a in enumerate(names):
        va = data[a]["vec"]
        for b in names[i + 1:]:
            out.append((dot(va, data[b]["vec"]), a, b))
    out.sort(reverse=True)
    return out


def cmd_report(data):
    knowledge = [n for n, p in data.items() if p["type"] in ("concept", "entity", "analysis")]
    allp = pairs(data, knowledge)
    # thresholds from the distribution, so they adapt to the model
    sims = [s for s, _, _ in allp]
    p99 = sims[max(0, len(sims) // 100)]
    def capped(rows, limit, per_page=2):
        """At most `per_page` rows per page, so a family of templated pages (the crates) can't fill the list."""
        seen, out = Counter(), []
        for s, a, b in rows:
            if seen[a] < per_page and seen[b] < per_page:
                out.append((s, a, b))
                seen[a] += 1
                seen[b] += 1
            if len(out) == limit:
                break
        return out

    def ladder(a, b):
        """One builds on the other: a foundation page and the rcfd page above it cite different kinds of source by design."""
        return b in data[a]["builds_on"] or a in data[b]["builds_on"]

    missing = capped([(s, a, b) for s, a, b in allp if s >= p99 and not linked(data, a, b)], 60)
    concepts = [n for n in knowledge if data[n]["type"] == "concept"]
    dup = capped(pairs(data, concepts), 25)
    nosrc = capped([(s, a, b) for s, a, b in allp if s >= p99 and data[a]["sources"] and data[b]["sources"]
                    and not set(data[a]["sources"]) & set(data[b]["sources"]) and not ladder(a, b)], 30)

    lines = [BEGIN, "",
             f"Model `{MODEL}`, {len(data)} pages, {len(knowledge)} concept/entity/analysis pages compared pairwise on "
             f"{date.today().isoformat()}. Similarity is the cosine of the mean section embeddings; the cut for "
             f"'very similar' is the top 1 % of pairs (cos >= {p99:.3f}). These are candidates for the judgement pass of lint, not findings.", "",
             f"## Missing links ({len(missing)})", "",
             "Very similar pages that neither link nor cite each other. Add a link where the relation is real.", ""]
    lines += [f"- {s:.3f} [[{a}]] — [[{b}]]" for s, a, b in missing] or ["- none"]
    lines += ["", f"## Most similar concept pairs ({len(dup)})", "",
              "Check for overlap or duplicated scope (merge, split or cross-reference; the page-structure review).", ""]
    lines += [f"- {s:.3f} [[{a}]] — [[{b}]]{'' if linked(data, a, b) else ' (not linked)'}" for s, a, b in dup]
    lines += ["", f"## Similar pages with no shared source ({len(nosrc)})", "",
              "Same subject, disjoint evidence: where contradictions or unreconciled numbers tend to hide.", ""]
    lines += [f"- {s:.3f} [[{a}]] ({', '.join(data[a]['sources'][:3])}) — [[{b}]] ({', '.join(data[b]['sources'][:3])})"
              for s, a, b in nosrc] or ["- none"]
    lines += ["", END]
    block = "\n".join(lines)

    if REPORT.exists():
        text = REPORT.read_text(encoding="utf-8")
    else:
        today = date.today().isoformat()
        text = f"""---
type: analysis
tags: [lint, relatedness, embeddings]
sources: []
created: {today}
updated: {today}
status: draft
---

# Related candidates

Generated by `tools/search.py report` from local embeddings (Ollama). Input for the judgement pass of lint: missing cross-links, overlapping pages and places where contradictions may hide. Work through it, then rerun. See also [[open-gaps]] and [[stale-report]].

{BEGIN}
{END}
"""
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    text = pre + block + post
    text = re.sub(r"^updated: .*$", f"updated: {date.today().isoformat()}", text, count=1, flags=re.M)
    REPORT.write_text(text, encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}: {len(missing)} missing links, {len(nosrc)} no-shared-source pairs")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("index")
    s = sub.add_parser("search"); s.add_argument("query"); s.add_argument("-k", type=int, default=10)
    m = sub.add_parser("similar"); m.add_argument("page"); m.add_argument("-k", type=int, default=10)
    sub.add_parser("report")
    args = ap.parse_args()
    data = index(load_pages(), quiet=args.cmd in ("search", "similar"))
    if args.cmd == "search":
        cmd_search(data, args.query, args.k)
    elif args.cmd == "similar":
        cmd_similar(data, args.page.removesuffix(".md").split("/")[-1], args.k)
    elif args.cmd == "report":
        cmd_report(data)


if __name__ == "__main__":
    main()
