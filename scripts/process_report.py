def read(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as fh:
        return fh.read()


def exists(root, rel):
    return os.path.isfile(os.path.join(root, rel))


def exceptions(root, name):
    """The entries of docs/process/exceptions/<name>.txt, or None when the file does not exist (the rule has not started)."""
    rel = f"{EXC_DIR}/{name}.txt"
    if not exists(root, rel):
        return None
    return {ln.strip() for ln in read(root, rel).splitlines() if ln.strip() and not ln.startswith("#")}


def less_exceptions(root, name, found):
    """(new findings, stale exceptions). With no exceptions file nothing is new: the rule has not started."""
    exc = exceptions(root, name)
    if exc is None:
        return [], []
    found = set(found)
    return sorted(found - exc), sorted(exc - found)


