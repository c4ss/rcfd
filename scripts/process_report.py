def seed(root, items, md, adrs, history):
    """Write today's findings as the exceptions files. Run once when a rule starts; afterwards the files only shrink."""
    os.makedirs(os.path.join(root, EXC_DIR), exist_ok=True)
    ids = Counter(i["id"] for i in items)
    mdc = Counter(i for i, _ in md)
    st = {i["id"]: i["status"] for i in items}
    md_st = {}
    for i, s in md:
        md_st.setdefault(i, s)
    _, _, rust, specs = sec_l(root, items, adrs)
    files = {
        "roadmap-duplicates": [f"json {k}" for k, v in ids.items() if v > 1] + [f"md {k}" for k, v in mdc.items() if v > 1],
        "roadmap-status-differs": [i for i in st if md_st.get(i) != st[i]] + [i for i in md_st if i not in st],
        "partial-without-gap": [i["id"] for i in items if i["status"] == "partial" and not i.get("gap")],
        "adr-without-kind-word": [a["file"] for a in adrs if not a["kind"]],
        "test-root-without-adr": rust,
        "studio-spec-without-record": specs,
        "from-memory-count": [str(sum(1 for a in adrs if re.search(r"from memory", a["text"], re.I)))],
    }
    notes = {
        "roadmap-duplicates": "Ids that occur twice in the roadmap pair when the check started.",
        "roadmap-status-differs": "Items whose status differed between roadmap.json and ROADMAP.md when the check started.",
        "partial-without-gap": "Partial items that had no `gap` key when the rule started (agent rules, rule 9).",
        "adr-without-kind-word": "ADR file names without a kind word when the rule started.",
        "test-root-without-adr": "Rust test root files whose leading comment named no ADR when the rule started.",
        "studio-spec-without-record": "Studio spec files whose leading comment named no item or ADR when the rule started.",
        "from-memory-count": "The number of ADRs that cite from memory. It may fall, never rise.",
        "adr-rewritten": "ADRs with lines deleted after their creating commit when the append-only rule started.",
        "registration-not-alone": "Registrations whose creating commit changed other files when the lint started.",
        "registration-after-code": "Registrations created after a code commit that cites them when the lint started.",
    }
    if history:
        for name in ("adr-rewritten", "registration-not-alone", "registration-after-code"):
            files[name] = []
        # sec_c reports new findings only against an existing file, so collect them with empty files in place first
        for name in ("adr-rewritten", "registration-not-alone", "registration-after-code"):
            with open(os.path.join(root, EXC_DIR, name + ".txt"), "w", encoding="utf-8", newline="\n") as fh:
                fh.write("")
        _, fail = sec_c(root, adrs)
        for f in fail:
            what, _, name = f.rpartition(", ")
            key = ("adr-rewritten" if "appending" in what else "registration-not-alone" if "alone" in what else "registration-after-code")
            files[key].append(name)
    for name, entries in files.items():
        with open(os.path.join(root, EXC_DIR, name + ".txt"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(f"# {notes[name]}\n# Written by scripts/process_report.py --seed-exceptions on {datetime.date.today().isoformat()}. "
                     "This list only shrinks.\n" + "".join(e + "\n" for e in sorted(set(entries))))
        print(f"{EXC_DIR}/{name}.txt: {len(set(entries))}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--weekly", action="store_true")
    ap.add_argument("--history", action="store_true")
    ap.add_argument("--sections", default="")
    ap.add_argument("--seed-exceptions", action="store_true")
    ap.add_argument("--list-generated", action="store_true", help="print the paths --write keeps current, one per line")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    items, cats, adrs, md = load_items(root), load_categories(root), load_adrs(root), roadmap_md(root)

    if a.seed_exceptions:
        seed(root, items, md, adrs, a.history)
        return 0
    gen = generated(root, items, cats, adrs)
    if a.list_generated:
        print(chr(10).join(sorted(gen)))
        return 0
    if a.write:
        for rel, text in gen.items():
            old = read(root, rel) if exists(root, rel) else None
            if old != text:
                with open(os.path.join(root, rel), "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
                print(f"wrote {rel}")
        return 0

    want = set(a.sections.split(",")) if a.sections else None
    fails, out = [], []

    def show(key, title, rep):
        if want is None or key in want:
            out.append(f"({key}) {title}")
            out.extend("  " + r if not r.startswith("  ") else r for r in rep)
            out.append("")

    rep, f = sec_a(root, items, md); fails += f; show("a", "roadmap checks", rep)
    rep, f = sec_b(root, adrs); fails += f; show("b", "ADR records", rep)
    if a.history:
        rep, f = sec_c(root, adrs); fails += f; show("c", "registration lint (git history)", rep)
    rep, questions = sec_d(items, adrs, full=want == {"d"}); show("d", "open questions", rep)
    rep, f, mem, unv = sec_e(root, adrs); fails += f; show("e", "provenance", rep)
    rep, f = sec_r(root, adrs); fails += f; show("r", "registrations under the rules in the repository", rep)
    show("f", "overview numbers", sec_f(root, items, cats))
    rep, over = sec_g(root, items, cats, adrs); show("g", "dispatch", rep)
    rep, _ = sec_h(root); show("h", "the lead's state", rep)
    show("i", "area pages", sec_i(root, items, cats))
    rep, f = sec_k(root); fails += f; show("k", "merge hygiene", rep)
    rep, f, rust, specs = sec_l(root, items, adrs); fails += f; show("l", "test headers", rep)
    if a.history:
        r = subprocess.run([sys.executable, os.path.join(root, "scripts", "adr_test_index.py"), "--root", root, "--report"],
                           capture_output=True, text=True, encoding="utf-8", errors="replace")
        show("t", "tests and their primary ADR (scripts/adr_test_index.py --report)", (r.stdout or r.stderr).strip().splitlines()[-25:])
    measures = sec_m(root, items, cats, adrs, questions, mem, rust, specs)
    show("m", "process measures", measures)
    for rel, text in gen.items():
        if not exists(root, rel) or read(root, rel) != text:
            fails.append(f"generated file is not current: {rel} (run python scripts/process_report.py --write)")

    if a.weekly:
        print("\n".join(sec_j(root, items, cats, questions, over)))
        print("\nProcess measures")
        print("\n".join("  " + m for m in measures))
        return 0
    if a.check:
        for f in fails:
            print("FAIL", f)
        print(f"process report check: {len(fails)} failure(s)")
        return 1 if fails else 0
    print("\n".join(out))
    if fails:
        print(f"{len(fails)} check failure(s); see --check")
    return 0


if __name__ == "__main__":
    sys.exit(main())
