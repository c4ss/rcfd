def sec_a(root, items, md):
    """Roadmap checks. Returns (report lines, failures)."""
    rep, fail = [], []
    ids = [i["id"] for i in items]
    dup_json = sorted(k for k, v in Counter(ids).items() if v > 1)
    dup_md = sorted(k for k, v in Counter(i for i, _ in md).items() if v > 1)
    st = {i["id"]: i["status"] for i in items}
    md_st = {}
    for i, s in md:
        md_st.setdefault(i, s)
    differ = sorted(f"{i} json={st[i]} md={md_st.get(i, 'absent')}" for i in st if md_st.get(i) != st[i])
    differ += sorted(f"{i} json=absent md={md_st[i]}" for i in md_st if i not in st)
    new, stale = less_exceptions(root, "roadmap-duplicates", [f"json {i}" for i in dup_json] + [f"md {i}" for i in dup_md])
    rep.append(f"duplicate ids: roadmap.json {len(dup_json)}, ROADMAP.md {len(dup_md)} {dup_md}")
    fail += [f"a: duplicate id, {x}" for x in new]
    new_d, stale_d = less_exceptions(root, "roadmap-status-differs", [x.split()[0] for x in differ])
    rep.append(f"status differs between roadmap.json and ROADMAP.md: {len(differ)}" + ("" if not differ else ": " + "; ".join(differ[:10])))
    fail += [f"a: status differs, {x}" for x in new_d]
    no_gap = [i["id"] for i in items if i["status"] == "partial" and not i.get("gap")]
    long_gap = [i["id"] for i in items if len(i.get("gap") or "") > GAP_MAX]
    stray_gap = [i["id"] for i in items if i.get("gap") and i["status"] != "partial"]
    new_g, stale_g = less_exceptions(root, "partial-without-gap", no_gap)
    rep.append(f"partial items without gap: {len(no_gap)} (of {sum(1 for i in items if i['status'] == 'partial')} partial)")
    rep.append(f"gap over {GAP_MAX} characters: {len(long_gap)} {long_gap[:10]}; gap on an item that is not partial: {len(stray_gap)} {stray_gap[:10]}")
    fail += [f"a: partial item without gap, {x}" for x in new_g]
    fail += [f"a: gap over {GAP_MAX} characters, {x}" for x in long_gap] + [f"a: gap on an item that is not partial, {x}" for x in stray_gap]
    soft = [i["id"] for i in items if not re.search(r"\d", i.get("acceptance") or "") and "registration" not in (i.get("acceptance") or "")]
    rep.append(f"acceptance with no number and no hand-over to the registration (reported, not refused): {len(soft)}")
    for name, s in (("roadmap-duplicates", stale), ("roadmap-status-differs", stale_d), ("partial-without-gap", stale_g)):
        if s:
            rep.append(f"exceptions that no longer apply in {name}.txt (remove them): {len(s)} {s[:8]}")
    return rep, fail


def index_text(adrs, items, cats):
    """docs/adr/index.md."""
    st = {i["id"]: i["status"] for i in items}
    cat = item_category(cats)
    cited = defaultdict(list)
    for i in items:
        for n in sorted(set(re.findall(r"ADR (\d{4})", i.get("note") or ""))):
            cited[n].append(i["id"])
    groups = defaultdict(list)
    for a in adrs:
        named = [i for i in a["items"] if i in st]
        if named:
            for i in named:
                groups[cat.get(i, "Other")].append((a, i))
        else:
            groups[None].append((a, ""))
    out = ["# ADR index", "",
           "One row per record of this folder, grouped by the roadmap category of the item in its file name. Generated by "
           "`python scripts/process_report.py --write` from the files of this folder, `docs/roadmap.json` and the category "
           "list of `scripts/roadmap_progress.py`; only the lead regenerates it, on main. The status word and date are those of "
           "the record's status line, which is a creation stamp; the outcome of the work is the item status.", ""]

    def row(a, item):
        link = f"[{a['n']}]({a['file']})"
        title = a["title"].replace("|", "\\|")
        return f"| {link} | {title} | {a['status']} | {a['date']} | {a['addenda']} | {item} | {st.get(item, '')} |"

    head = ["| ADR | Title | Status word | Date | Addenda | Item | Item status |", "|---|---|---|---|---|---|---|"]
    for _, name, _ in cats + [("", "Other", [])]:
        if name not in groups:
            continue
        rows = sorted(groups[name], key=lambda r: (r[0]["n"], r[1]))
        out += [f"## {name} ({len(rows)})", ""] + head + [row(a, i) for a, i in rows] + [""]
    rest = sorted(groups.get(None, []), key=lambda r: r[0]["n"])
    out += [f"## Records with no item in the file name ({len(rest)})", "",
            "| ADR | Title | Status word | Date | Addenda | Items whose note cites it |", "|---|---|---|---|---|---|"]
    for a, _ in rest:
        c = cited.get(a["n"], [])
        cell = ", ".join(c[:12]) + (f" and {len(c) - 12} more" if len(c) > 12 else "")
        title = a["title"].replace("|", "\\|")
        out.append(f"| [{a['n']}]({a['file']}) | {title} | {a['status']} | {a['date']} | {a['addenda']} | {cell} |")
    return "\n".join(out) + "\n"


