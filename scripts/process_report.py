def sec_i(root, items, cats):
    cat = item_category(cats)
    rep = []
    for _, name, _ in cats:
        page = AREA_PAGES.get(name)
        done = [i["id"] for i in items if i["status"] == "done" and cat.get(i["id"]) == name]
