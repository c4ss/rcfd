def sec_k(root):
    rep, fail = [], []
    bad = []
    for p in git(root, "ls-files").splitlines():
        full = os.path.join(root, p)
        try:
            if os.path.getsize(full) > 30_000_000:
                continue
            with open(full, "rb") as fh:
                data = fh.read()
        except OSError:
            continue
        if b"\n<<<<<<< " in data or b"\n>>>>>>> " in data or data.startswith(b"<<<<<<< "):
            bad.append(p)
    rep.append(f"tracked files with a conflict marker line: {len(bad)} {bad[:8]}")
    fail += [f"k: conflict marker in {p}" for p in bad]
    src = read(root, "scripts/roadmap_progress.py")
    if "--check" in src:
        r = subprocess.run([sys.executable, os.path.join(root, "scripts", "roadmap_progress.py"), "--check"], capture_output=True, text=True, cwd=root)
        rep.append("roadmap SVGs equal what scripts/roadmap_progress.py writes: " + ("yes" if r.returncode == 0 else "NO"))
        if r.returncode:
            fail.append("k: a roadmap SVG differs from what scripts/roadmap_progress.py writes: " + (r.stderr or r.stdout).strip()[:200])
    else:
        rep.append("roadmap SVGs: scripts/roadmap_progress.py has no --check mode; not compared")
    return rep, fail


def leading_comment(path, marks=("//",)):
    out = []
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for ln in fh:
                st = ln.strip()
                if st and not st.startswith(marks):
                    break
                out.append(st)
    except OSError:
        pass
    return "\n".join(out)


def sec_l(root, items, adrs):
    rep, fail = [], []
    known = {a["n"] for a in adrs}
    ids = {i["id"] for i in items}
    rust, specs = [], []
    for p in git(root, "ls-files", "crates/*/tests/*.rs").splitlines():
        if p.count("/") != 3:
            continue
        head = leading_comment(os.path.join(root, p), ("//", "#!["))
        if not any(n in known for n in re.findall(r"\bADR (\d{4})\b", head)):
            rust.append(p)
    for p in git(root, "ls-files", "apps/studio-web/*.spec.ts").splitlines():
        head = leading_comment(os.path.join(root, p), ("//", "/*", "*"))
        ok = any(n in known for n in re.findall(r"\bADR (\d{4})\b", head)) or any(i in ids for i in re.findall(r"\bF-\d{3}\b", head))
        if not ok:
            specs.append(p)
    n1, s1 = less_exceptions(root, "test-root-without-adr", rust)
    n2, s2 = less_exceptions(root, "studio-spec-without-record", specs)
    rep.append(f"Rust test root files whose leading comment names no existing ADR: {len(rust)}")
    rep.append(f"Studio spec files whose leading comment names no item and no ADR: {len(specs)}")
    fail += [f"l: test file names no ADR in its leading comment, {x}" for x in n1]
    fail += [f"l: Studio spec names no item and no ADR in its leading comment, {x}" for x in n2]
    for name, s in (("test-root-without-adr", s1), ("studio-spec-without-record", s2)):
        if s:
            rep.append(f"exceptions that no longer apply in {name}.txt (remove them): {len(s)}")
    return rep, fail, rust, specs


def since_green(root):
    """(merges on main's first-parent line since the newest green full run, that run's commit)."""
    green = [r for r in load_ledger(root) if r.get("kind") == "gate" and r.get("result") == "green"]
    base = green[-1]["commit"] if green else LAST_GREEN
    try:
        n = int(git(root, "rev-list", "--count", "--first-parent", "--merges", f"{base}..HEAD").strip())
    except (subprocess.CalledProcessError, ValueError):
        n = None
    return n, base


