def load_categories(root):
    """CATEGORIES of scripts/roadmap_progress.py, read with ast (the script draws at import, so it is not imported)."""
    tree = ast.parse(read(root, "scripts/roadmap_progress.py"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "CATEGORIES" for t in node.targets):
            return [(fam, name, list(ids)) for fam, name, ids in ast.literal_eval(node.value)]
    raise SystemExit("scripts/roadmap_progress.py has no CATEGORIES list")


def item_category(cats):
    return {f"F-{n:03d}": name for _, name, ids in cats for n in ids}


def roadmap_md(root):
    """[(id, status)] in page order from the checkboxes of docs/ROADMAP.md."""
    out = []
    for ln in read(root, "docs/ROADMAP.md").splitlines():
        m = ROADMAP_ITEM.match(ln)
        if m:
            out.append((m.group(2), BOX[m.group(1)]))
    return out


def priority(root, cats):
    """The priority statement of docs/ROADMAP.md (I6): its date, and its lines in order as (category, weekly budget or None)
    when the statement is a numbered list of category names. Otherwise the categories in the script's order and no date."""
    text = read(root, "docs/ROADMAP.md")
    m = re.search(r"^Current priority \(set by the maintainer, (\d{4}-\d{2}-\d{2})\):?(.*?)(?:\n\n|\Z)", text, re.M | re.S)
    names = [name for _, name, _ in cats]
    if not m:
        return None, [(n, None) for n in names], False
    lines = []
    for ln in m.group(2).splitlines():
        lm = re.match(r"\s*\d+\.\s+(.*)", ln)
        if not lm:
            continue
        for n in names:
            if lm.group(1).startswith(n):
                b = re.search(r"budget (\d+)", lm.group(1))
                lines.append((n, int(b.group(1)) if b else None))
    if not lines:
        return m.group(1), [(n, None) for n in names], False
    rest = [(n, None) for n in names if n not in {x for x, _ in lines}]
    return m.group(1), lines + rest, True


def load_adrs(root):
    """One record per file of docs/adr: number, file, title, status word, status date, addenda, items in the name, kind."""
    out = []
    d = os.path.join(root, "docs", "adr")
    for fn in sorted(os.listdir(d)):
        m = ADR_FILE.match(fn)
        if not m:
            continue
        text = read(root, f"docs/adr/{fn}")
        head = text[:4000]
        title = re.sub(r"^#\s*(ADR \d{4}:?\s*)?", "", head.splitlines()[0]).strip() if head else ""
        sm = re.search(r"^Status:\s*\**\s*([A-Za-z]+)([^\n]*)", head, re.M)
        word = sm.group(1).upper() if sm else ""
        dm = re.search(r"\d{4}-\d{2}-\d{2}", sm.group(2)) if sm else None
        out.append({
            "n": m.group(1), "file": fn, "title": title, "status": word, "date": dm.group(0) if dm else "",
            "addenda": len(re.findall(r"^#{1,4}\s*Addendum\b", text, re.M)),
            "items": [f"F-{int(x):03d}" for x in re.findall(r"(?:^|-)f(\d+)(?=-)", m.group(2))],
            "kind": next((k for k in KIND_WORDS if k in m.group(2).split("-") or k in m.group(2)), ""),
            "text": text,
        })
    return out


def load_ledger(root):
    if not exists(root, LEDGER):
        return []
    lines = [ln for ln in read(root, LEDGER).splitlines() if ln.strip() and not ln.startswith("#")]
    if not lines:
        return []
    cols = lines[0].split("\t")
    return [dict(zip(cols, ln.split("\t"))) for ln in lines[1:]]


def load_briefs(root):
    out = []
    d = os.path.join(root, BRIEFS)
    for fn in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if not fn.endswith(".md") or fn == "README.md":
            continue
        text = read(root, f"{BRIEFS}/{fn}")

        def field(name):
            m = re.search(rf"^{re.escape(name)}:\s*(.*)$", text, re.M)
            return m.group(1).strip() if m else ""

        out.append({"file": fn, "branch": field("Branch") or fn[:-3], "items": re.findall(r"F-\d+", field("Items")),
                    "issued": field("Issued"), "rules": field("Rules version"), "model": field("Model"),
                    "closed": bool(re.search(r"^Closed without merge", text, re.M))})
    return out


