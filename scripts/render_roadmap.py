#!/usr/bin/env python3
"""Render the item list of docs/ROADMAP.md from docs/roadmap.json (docs/process/documentation-process-review.md, I4: the
generator of 2026-10-31, commit 5755656d, revived for today's roadmap). Python 3.9 standard library only.

docs/ROADMAP.md keeps a hand-written head (the title, the priority statement, the conventions) down to a marker line. Everything
after the marker is generated: the items by phase in id order, each with its checkbox, title, prerequisites, acceptance, `gap`
(partial items) and note. roadmap.json is the one source; the page cannot differ from it.

Usage (from the repository root):
    python scripts/render_roadmap.py --diff     list where today's hand-kept page differs from roadmap.json (titles, acceptance,
                                                notes, ids, duplicates). Read-only. The lead reconciles these in roadmap.json
                                                before adopting, because adopting keeps roadmap.json's text and drops the page's.
    python scripts/render_roadmap.py --adopt    once, on main: put the marker before the first phase heading and generate.
                                                Refuses while --diff reports a difference in text, unless --json-wins is given.
    python scripts/render_roadmap.py            rewrite the generated part (the page must have the marker)
    python scripts/render_roadmap.py --check    write nothing; exit 1 when roadmap.json breaks the schema or the generated part
                                                is stale. Before adoption only the schema is checked.

Schema of an item: id, title, phase, deps, status (done, partial, todo), acceptance, note, and for a partial item an optional
`gap` of at most 500 characters. Ids are unique and every dep is an id.
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON, PAGE = "docs/roadmap.json", "docs/ROADMAP.md"
MARKER = "<!-- roadmap:items (generated by scripts/render_roadmap.py from roadmap.json; do not edit below this line) -->"
PHASES = {0: "Workspace and architecture", 1: "Mesh data structures and IO", 2: "Finite-volume core and linear solvers",
          3: "Turbulence", 4: "Heat transfer and species", 5: "Compressible flow", 6: "Post-processing and VTK output",
          7: "Scripting API, CLI and settings tree", 8: "AI assistant and desktop app integration",
          9: "Advanced physics and scale (stretch)"}
MARK = {"done": "x", "partial": "~", "todo": " "}
KEYS = {"id", "title", "phase", "deps", "status", "acceptance", "note", "gap"}
REQUIRED = {"id", "title", "phase", "deps", "status", "acceptance"}
GAP_MAX = 500
ITEM = re.compile(r"^- \[(x|~| )\] \*\*(F-\d+)\*\* (.*)")
FIELD = re.compile(r"^  - (depends on|acceptance|gap|note): (.*)")


def load(root):
    with open(os.path.join(root, JSON), encoding="utf-8") as fh:
        data = json.load(fh)
    return data["items"] if isinstance(data, dict) else data


def schema_problems(items):
    out, seen = [], set()
    ids = {i.get("id") for i in items}
    for i in items:
        k = i.get("id", "?")
        if k in seen:
            out.append(f"{k}: id occurs twice")
        seen.add(k)
        if not re.fullmatch(r"F-\d{3,4}", str(k)):
            out.append(f"{k}: id is not F-NNN")
        if set(i) - KEYS:
            out.append(f"{k}: unknown key {sorted(set(i) - KEYS)}")
        if REQUIRED - set(i):
            out.append(f"{k}: missing key {sorted(REQUIRED - set(i))}")
            continue
        if i["status"] not in MARK:
            out.append(f"{k}: status {i['status']!r}")
        if i["phase"] not in PHASES:
            out.append(f"{k}: phase {i['phase']!r}")
        for d in i["deps"]:
            if d not in ids:
                out.append(f"{k}: dep {d} is not an item")
        gap = i.get("gap")
        if gap is not None:
            if i["status"] != "partial":
                out.append(f"{k}: gap on an item that is not partial")
            if not gap.strip() or len(gap) > GAP_MAX or "\n" in gap:
                out.append(f"{k}: gap must be one line of 1 to {GAP_MAX} characters")
    return out


def one_line(text):
    return re.sub(r"\s+", " ", text or "").strip()


def item_block(it):
    out = [f"- [{MARK[it['status']]}] **{it['id']}** {one_line(it['title'])}",
           f"  - depends on: {', '.join(it.get('deps') or []) or 'none'}",
           f"  - acceptance: {one_line(it['acceptance'])}"]
    if it.get("gap"):
        out.append(f"  - gap: {one_line(it['gap'])}")
    if it.get("note"):
        out.append(f"  - note: {one_line(it['note'])}")
    return out


def render_items(items):
    out = [MARKER, ""]
    for ph in sorted(PHASES):
        group = sorted((i for i in items if i["phase"] == ph), key=lambda i: int(i["id"][2:]))
        if not group:
            continue
        c = {s: sum(1 for i in group if i["status"] == s) for s in MARK}
        out += [f"## Phase {ph} - {PHASES[ph]}", "",
                f"{len(group)} items: {c['done']} done, {c['partial']} partly done, {c['todo']} not started.", ""]
        for it in group:
            out += item_block(it)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def split_page(text):
    """(head, generated part or None)."""
    if MARKER not in text:
        return text, None
    i = text.index(MARKER)
    return text[:i], text[i:]


def render_page(text, items):
    """The whole page with its generated part current, or None when the page has no marker."""
    head, gen = split_page(text)
    return None if gen is None else head + render_items(items)


def page_items(text):
    """{id: [{status, title, deps, acceptance, gap, note}, ...]} read from the page as it is kept by hand."""
    out, cur, field = {}, None, None
    for ln in text.splitlines():
        m = ITEM.match(ln)
        if m:
            cur = {"status": {v: k for k, v in MARK.items()}[m.group(1)], "title": m.group(3)}
            out.setdefault(m.group(2), []).append(cur)
            field = "title"
            continue
        if cur is None:
            continue
        if ln.startswith("#") or ln.startswith("<!--"):
            cur = None
            continue
        f = FIELD.match(ln)
        if f:
            field = {"depends on": "deps"}.get(f.group(1), f.group(1))
            cur[field] = f.group(2)
        elif ln.strip() and ln.startswith(" "):
            part = ln.strip()  # a wrapped line, or a sub-bullet of the field: its "- " is layout, a " - " inside a line is a minus
            cur[field] = cur.get(field, "") + " " + (part[2:] if part.startswith("- ") else part)
        elif ln.strip():
            cur = None  # a paragraph between items
    return out


def norm(text):
    """Text compared without layout: wrapped lines and backticks do not count (page_items drops the sub-bullet marks)."""
    return re.sub(r"\s+", " ", (text or "").replace("`", "")).strip()


def diff(text, items):
    """[(kind, id, detail)] where the hand-kept page and roadmap.json disagree. kind 'text' loses words on adoption."""
    page = page_items(text)
    out = []
    by_id = {i["id"]: i for i in items}
    for k, blocks in page.items():
        if len(blocks) > 1:
            out.append(("duplicate", k, f"{len(blocks)} entries on the page"))
        if k not in by_id:
            out.append(("id", k, "on the page, not in roadmap.json"))
            continue
        it, b = by_id[k], blocks[0]
        if b["status"] != it["status"]:
            out.append(("status", k, f"page {b['status']}, json {it['status']}"))
        deps = ", ".join(it.get("deps") or []) or "none"
        if norm(b.get("deps", "none")) != norm(deps):
            out.append(("deps", k, f"page {b.get('deps')!r}, json {deps!r}"))
        for f in ("title", "acceptance", "note"):
            p, j = norm(b.get(f, "")), norm(it.get(f) or "")
            if p != j:
                n = next((x for x, (a, c) in enumerate(zip(p, j)) if a != c), min(len(p), len(j)))
                out.append(("text", k, f"{f}: page {len(p)} characters, json {len(j)}; first difference at {n}: "
                            f"page {p[n:n + 60]!r}, json {j[n:n + 60]!r}"))
    for k in by_id:
        if k not in page:
            out.append(("id", k, "in roadmap.json, not on the page"))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--diff", action="store_true")
    ap.add_argument("--adopt", action="store_true")
    ap.add_argument("--json-wins", action="store_true")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    items = load(root)
    path = os.path.join(root, PAGE)
    with open(path, encoding="utf-8") as fh:
        text = orig = fh.read()
    problems = schema_problems(items)
    head, gen = split_page(text)

    if a.diff:
        if gen is not None:
            print("the page is generated; it cannot differ from roadmap.json")
            return 0
        d = diff(text, items)
        for kind, k, detail in d:
            print(f"{kind}\t{k}\t{detail}")
        kinds = {}
        for kind, _, _ in d:
            kinds[kind] = kinds.get(kind, 0) + 1
        print(f"{len(d)} difference(s): " + (", ".join(f"{k} {v}" for k, v in sorted(kinds.items())) or "none"))
        return 0
    for p in problems:
        print("schema:", p)
    if a.check:
        if gen is None:
            print(f"{PAGE} is kept by hand (no marker); schema problems: {len(problems)}")
            return 1 if problems else 0
        stale = render_page(text, items) != text
        if stale:
            print(f"{PAGE} is not what roadmap.json renders: run python scripts/render_roadmap.py")
        return 1 if problems or stale else 0
    if problems:
        return 1
    if a.adopt:
        if gen is not None:
            print("already adopted")
            return 0
        lost = [x for x in diff(text, items) if x[0] in ("text", "id", "deps")]
        if lost and not a.json_wins:
            print(f"{len(lost)} difference(s) would be lost; see --diff, reconcile them in roadmap.json, or pass --json-wins")
            return 1
        m = re.search(r"^## ", text, re.M)
        if not m:
            print("no heading to put the marker before")
            return 1
        text = text[:m.start()] + MARKER + "\n"
    elif gen is None:
        print(f"{PAGE} has no marker: the page is still kept by hand. See --diff and --adopt.")
        return 1
    new = render_page(text, items)
    if new != orig:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
        print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
