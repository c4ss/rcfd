#!/usr/bin/env python3
"""Per cent complete for the whole roadmap and for each simulation milestone (F-865, ADR 0756). Python 3.9 standard library.

A simulation milestone is a named simulation with a stated result. docs/milestones.json defines each one:

    {"milestones": [{"id": "vortex-shedding", "title": "...", "result": "...", "cases": ["..."], "reference": "...",
                     "headline": ["F-029"], "page": "docs/..."}]}        (page is optional)

An item of docs/roadmap.json names the milestones it belongs to in its key `milestones`. A headline item is an item whose
acceptance is the milestone's comparison with its published reference. This script checks the two files against each other
and writes the figures as a generated block of docs/roadmap-overview.md, between markers of its own.

Usage (from the repository root):
    python scripts/roadmap_milestones.py            rewrite the block (the page must carry the markers; see --install)
    python scripts/roadmap_milestones.py --check    write nothing; exit 1 when the files disagree or the block is not current
    python scripts/roadmap_milestones.py --install  put the markers after the process report's block of the overview, once
    python scripts/roadmap_milestones.py --apply MAPPING [--definitions FILE]
                                                    set the keys in docs/roadmap.json from a mapping file, one line per
                                                    membership: <item id> tab <milestone id> tab <reason>; lines that start
                                                    with # are comments. The members of every milestone the mapping names are
                                                    replaced; other milestones are left. --definitions copies FILE to
                                                    docs/milestones.json first. Nothing is written if the result is not valid.

The figures: items done, partly done and not started, and the per cent with a partly done item as one half, as the overview
counts. A headline item reads "met" when done, "partly met" with its gap when partial and "not started" when todo; a milestone
reads "met" only when every headline item is done, "not started" when none has started, and "not met" otherwise. The per cent
never decides the word. With no key in the roadmap and no definitions file there is nothing to check and nothing is written.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import render_roadmap as rr  # noqa: E402

ROOT = rr.ROOT
DEFS, OVERVIEW = "docs/milestones.json", "docs/roadmap-overview.md"
BEGIN = "<!-- roadmap-milestones begin (generated by scripts/roadmap_milestones.py; do not edit) -->"
END = "<!-- roadmap-milestones end -->"
ANCHOR = "<!-- process-report:overview end -->"
DEF_KEYS = {"id", "title", "result", "cases", "reference", "headline", "page"}
DEF_REQUIRED = DEF_KEYS - {"page"}
SHAPE = "milestones: the definitions must be {\"milestones\": [...]}"


def read(root, rel):
    with open(os.path.join(root, rel), "rb") as fh:
        return fh.read().decode("utf-8")


def write(root, rel, text):
    with open(os.path.join(root, rel), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def load_definitions(root, rel=DEFS):
    """(definitions or None when the file does not exist, problems of reading it)."""
    if not os.path.isfile(os.path.join(root, rel)):
        return None, []
    try:
        return json.loads(read(root, rel)), []
    except ValueError as e:
        return None, [f"milestones: {rel} is not JSON ({e})"]


def strings(value):
    return isinstance(value, list) and all(isinstance(v, str) and v.strip() for v in value)


def definition_problems(defs, root=None):
    """V6: the form of the definitions."""
    if not (isinstance(defs, dict) and set(defs) == {"milestones"} and isinstance(defs["milestones"], list)
            and all(isinstance(m, dict) for m in defs["milestones"])):
        return [SHAPE]
    out, seen = [], set()
    for m in defs["milestones"]:
        k = m.get("id")
        if not (isinstance(k, str) and rr.MILESTONE_ID.fullmatch(k)):
            out.append(f"milestones: {k!r} is not a milestone id")
            continue
        if k in seen:
            out.append(f"milestones: '{k}' is defined twice")
        seen.add(k)
        if set(m) - DEF_KEYS:
            out.append(f"milestones: '{k}': unknown key {sorted(set(m) - DEF_KEYS)}")
        if DEF_REQUIRED - set(m):
            out.append(f"milestones: '{k}': missing key {sorted(DEF_REQUIRED - set(m))}")
            continue
        for f in ("title", "result", "reference"):
            if not (isinstance(m[f], str) and m[f].strip()):
                out.append(f"milestones: '{k}': {f} must be a non-empty string")
        if not strings(m["cases"]):
            out.append(f"milestones: '{k}': cases must be a list of strings")
        if not strings(m["headline"]):
            out.append(f"milestones: '{k}': headline must be a list of item ids")
        page = m.get("page")
        if page is not None:
            if not (isinstance(page, str) and page.startswith("docs/")):
                out.append(f"milestones: '{k}': page must be a path under docs/")
            elif root is not None and not os.path.isfile(os.path.join(root, page)):
                out.append(f"milestones: '{k}': page {page} does not exist")
    return out


def named(item):
    """The milestone ids an item names (a malformed key is render_roadmap's schema problem, not read here)."""
    ms = item.get("milestones")
    return [m for m in ms if isinstance(m, str)] if isinstance(ms, list) else []


def members(defs, items):
    """{milestone id: its member items in the order of the roadmap}."""
    return {m["id"]: [i for i in items if m["id"] in named(i)] for m in defs["milestones"]}


def problems(defs, items, root=None):
    """Every disagreement between the definitions and the keys (V1 to V7 of ADR 0756); [] when there is none."""
    keyed = [i for i in items if "milestones" in i]
    if defs is None:
        return ([f"milestones: {len(keyed)} item(s) have the key milestones and {DEFS} does not exist (first {keyed[0]['id']})"]
                if keyed else [])
    out = definition_problems(defs, root)
    if out:
        return out
    known = {m["id"] for m in defs["milestones"]}
    ids = {i["id"] for i in items}
    for i in keyed:
        for m in named(i):
            if m not in known:
                out.append(f"milestones: {i['id']} names the milestone '{m}', which is not defined")
    by = members(defs, items)
    for m in defs["milestones"]:
        k = m["id"]
        if not m["headline"]:
            out.append(f"milestones: '{k}' has no headline item")
        if not by[k]:
            out.append(f"milestones: '{k}' has no member")
        inside = {i["id"] for i in by[k]}
        for h in m["headline"]:
            if h not in ids:
                out.append(f"milestones: the headline item {h} of '{k}' is not an item")
            elif h not in inside and by[k]:
                out.append(f"milestones: the headline item {h} of '{k}' is not a member of it")
    return out


def counts(group):
    """(done, partly done, not started, per cent with a partly done item as one half): the overview's formula."""
    d, p, t = (sum(1 for i in group if i["status"] == s) for s in ("done", "partial", "todo"))
    n = d + p + t
    return d, p, t, (round(100 * (d + 0.5 * p) / n) if n else 0)


def headline_word(item):
    return {"done": "met", "partial": "partly met", "todo": "not started"}[item["status"]]


def milestone_word(headline_items):
    """"met" only when every headline item is done; never from the per cent."""
    words = {headline_word(i) for i in headline_items}
    if words == {"met"}:
        return "met"
    return "not started" if words == {"not started"} else "not met"


def cell(text):
    return rr.one_line(text).replace("|", "\\|")


def block(defs, items):
    """The generated block, without its markers. The definitions and keys must be valid."""
    by_id = {i["id"]: i for i in items}
    by = members(defs, items)
    d, p, t, pct = counts(items)
    out = ["### Simulation milestones", "",
           "A simulation milestone is a named simulation with a stated result. Its per cent counts the roadmap items that the "
           "simulation cannot be set up, run or trusted without, each partly done item as one half: it measures how much of "
           "that work has landed, not whether the result agrees. Only the column \"Headline result\" says that. It is read "
           "from the headline items, the items whose acceptance is the comparison with the published reference, and it is "
           "\"met\" only when every one of them is done. The milestones are defined in `docs/milestones.json`; an item names "
           "its milestones in `docs/roadmap.json`.", "",
           "| Milestone | Items | Done | Partly done | Not started | Per cent | Headline result |",
           "| --- | --- | --- | --- | --- | --- | --- |",
           f"| Whole roadmap | {len(items)} | {d} | {p} | {t} | {pct}% | not a milestone |"]
    for m in defs["milestones"]:
        d, p, t, pct = counts(by[m["id"]])
        word = milestone_word([by_id[h] for h in m["headline"]])
        out.append(f"| {cell(m['title'])} | {d + p + t} | {d} | {p} | {t} | {pct}% | {word} |")
    out += ["", "The headline items of each milestone:", ""]
    for m in defs["milestones"]:
        line = f"- **{rr.one_line(m['title'])}** (`{m['id']}`): {rr.one_line(m['result'])}"
        if m["cases"]:
            line += " Cases: " + ", ".join(f"`{c}`" for c in m["cases"]) + "."
        line += f" Reference: {rr.one_line(m['reference'])}."
        if m.get("page"):
            line += f" See [{m['page'][len('docs/'):]}]({m['page'][len('docs/'):]})."
        out.append(line)
        for h in m["headline"]:
            it = by_id[h]
            word = headline_word(it)
            tail = f" Gap: {rr.one_line(it.get('gap') or 'none stated')}" if word == "partly met" else ""
            out.append(f"  - {h}, {rr.one_line(it['title'])}: {word}.{tail}")
    return "\n".join(out)


def with_block(text, body):
    """The page with the block replaced, or None when the page has no markers."""
    if BEGIN not in text or END not in text:
        return None
    i, j = text.index(BEGIN) + len(BEGIN), text.index(END)
    return text[:i] + "\n" + body + "\n" + text[j:]


def read_mapping(text):
    """([(item id, milestone id, reason)], problems)."""
    rows, out, seen = [], [], set()
    for n, ln in enumerate(text.splitlines(), 1):
        if not ln.strip() or ln.startswith("#"):
            continue
        parts = [c.strip() for c in ln.split("\t")]
        if len(parts) != 3 or not all(parts):
            out.append(f"milestones: mapping line {n} is not <item id> tab <milestone id> tab <reason>")
            continue
        if (parts[0], parts[1]) in seen:
            out.append(f"milestones: mapping: {parts[0]} and '{parts[1]}' occur twice")
        seen.add((parts[0], parts[1]))
        rows.append(tuple(parts))
    return rows, out


def dumps(items):
    return json.dumps(items, indent=2, ensure_ascii=False) + "\n"


def apply(root, mapping_rel, defs_rel):
    """Set the keys from the mapping. (exit code, lines to print); writes only when everything is valid."""
    raw = read(root, rr.JSON)
    items = json.loads(raw)
    if not isinstance(items, list) or dumps(items) != raw:
        return 1, [f"milestones: {rr.JSON} is not laid out as this script writes it (a list, indent 2, no ASCII escapes, "
                   "one newline at the end); nothing written"]
    defs, out = load_definitions(root, defs_rel or DEFS)
    if defs is None and not out:
        out = [f"milestones: {defs_rel or DEFS} does not exist"]
    rows, bad = read_mapping(read(root, mapping_rel))
    out += bad
    if not out:
        out = definition_problems(defs, root)
    if out:
        return 1, out
    order = [m["id"] for m in defs["milestones"]]
    by_id = {i["id"]: i for i in items}
    for k, m, _ in rows:
        if k not in by_id:
            out.append(f"milestones: mapping: {k} is not an item")
        if m not in order:
            out.append(f"milestones: mapping: '{m}' is not defined")
    if out:
        return 1, out
    replaced = {m for _, m, _ in rows}
    want = {}
    for k, m, _ in rows:
        want.setdefault(k, set()).add(m)
    for it in items:
        keep = [m for m in named(it) if m not in replaced]
        new = sorted(set(keep) | want.get(it["id"], set()), key=lambda m: order.index(m) if m in order else len(order))
        if new:
            it["milestones"] = new
        else:
            it.pop("milestones", None)
    out = rr.schema_problems(items) + problems(defs, items, root)
    if out:
        return 1, out + ["milestones: nothing written"]
    lines = []
    if dumps(items) != raw:
        write(root, rr.JSON, dumps(items))
        lines.append(f"wrote {rr.JSON}: {len(rows)} membership(s) of {', '.join(m for m in order if m in replaced)}")
    if defs_rel and (not os.path.isfile(os.path.join(root, DEFS)) or read(root, DEFS) != read(root, defs_rel)):
        write(root, DEFS, read(root, defs_rel))
        lines.append(f"wrote {DEFS}")
    return 0, lines


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--install", action="store_true")
    ap.add_argument("--apply", metavar="MAPPING")
    ap.add_argument("--definitions", metavar="FILE")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    if a.definitions and not a.apply:
        ap.error("--definitions goes with --apply")
    if a.apply:
        if a.check:
            ap.error("--apply writes; it does not go with --check")
        code, lines = apply(root, a.apply, a.definitions)
        for ln in lines:
            print(ln)
        if code:
            return code
    items = rr.load(root)
    defs, out = load_definitions(root)
    out = out or problems(defs, items, root)
    for p in out:
        print(p)
    if out:
        return 1
    page = read(root, OVERVIEW) if os.path.isfile(os.path.join(root, OVERVIEW)) else ""
    if defs is None:
        if BEGIN in page:
            print(f"milestones: {OVERVIEW} carries the milestones block and {DEFS} does not exist")
            return 1
        return 0
    body = block(defs, items)
    if with_block(page, body) is None:
        if not a.install or a.check:
            print(f"milestones: {OVERVIEW} has no milestones block: run python scripts/roadmap_milestones.py --install")
            return 1
        if ANCHOR not in page:
            print(f"milestones: {OVERVIEW} has no line {ANCHOR} to put the block after")
            return 1
        i = page.index(ANCHOR) + len(ANCHOR)
        page = page[:i] + "\n\n" + BEGIN + "\n" + END + page[i:]
    new = with_block(page, body)
    if a.check:
        if new != page:
            print(f"milestones: {OVERVIEW}: the milestones block is not current: run python scripts/roadmap_milestones.py")
            return 1
        return 0
    if not os.path.isfile(os.path.join(root, OVERVIEW)) or new != read(root, OVERVIEW):
        write(root, OVERVIEW, new)
        print(f"wrote {OVERVIEW}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
