REPORT_BLOCK = ("<!-- process-report:overview begin (generated by scripts/process_report.py --write; do not edit) -->\n"
                "Of the 6 roadmap items, 3 are done.\n<!-- process-report:overview end -->")
OVERVIEW = "# Roadmap overview\n\n## Where it stands\n\n" + REPORT_BLOCK + "\n\n## What works today\n\n- Something.\n"
HEAD = "# rcfd roadmap\n\nPriority.\n\n"


def item(n, status, milestones=None, gap=None):
    it = {"id": f"F-{n:03d}", "title": f"Item {n}", "phase": 0, "deps": [], "status": status, "acceptance": f"check {n}",
          "note": ""}
    if gap:
        it["gap"] = gap
    if milestones:
        it["milestones"] = milestones
    return it


def items():
    """Six items, two milestones: wake = F-001 done (headline), F-002 todo; lift = F-001 done, F-003 partial (headline)."""
    return [item(1, "done", ["wake", "lift"]), item(2, "todo", ["wake"]),
            item(3, "partial", ["lift"], gap="the stall angle misses by 2 degrees"), item(4, "done"), item(5, "partial", gap="half"),
            item(6, "todo")]


def definitions():
    return {"milestones": [
        {"id": "wake", "title": "Wake of a cylinder", "result": "Strouhal number against the reference.",
         "cases": ["crates/x/tests/cylinder.rs"], "reference": "A paper, table 1", "headline": ["F-001"]},
        {"id": "lift", "title": "Lift of an aerofoil", "result": "Lift curve against the reference.", "cases": [],
         "reference": "A report, figure 2", "headline": ["F-003"]}]}


def line_of(problems, part):
    return [p for p in problems if part in p]


class Key(unittest.TestCase):
    """A1 and the item list: render_roadmap.py accepts the key and shows it; without it the bytes are today's."""

    def test_schema_accepts_the_key_and_names_a_malformed_one(self):
        self.assertEqual(rr.schema_problems(items()), [])
        for bad in ([], "wake", ["wake", "wake"], ["Wake"], [3], ["wake", ""]):
            its = items()
            its[3]["milestones"] = bad
            self.assertIn("F-004: milestones must be a list of one or more distinct milestone ids", rr.schema_problems(its), bad)

    def test_the_item_block_shows_the_milestones_after_the_deps(self):
        text = rr.render_items(items())
        self.assertIn("- [x] **F-001** Item 1\n  - depends on: none\n  - milestones: wake, lift\n  - acceptance: check 1\n", text)
        self.assertIn("- [x] **F-004** Item 4\n  - depends on: none\n  - acceptance: check 4\n", text)

    def test_without_the_key_the_item_list_is_what_it_was(self):
        plain = [{k: v for k, v in it.items() if k != "milestones"} for it in items()]
        text = rr.render_items(plain)
        self.assertNotIn("milestones", text)
        self.assertEqual(text.count("\n  - "), 6 * 2 + 2)  # deps and acceptance of six items, and two gaps
        page = HEAD + rr.render_items(items())
        self.assertEqual(rr.render_page(page, items()), page)
        self.assertEqual(rr.page_items(page)["F-001"][0]["milestones"], "wake, lift")


class Validation(unittest.TestCase):
    """A2: V1 to V7, each named."""

    def test_the_sample_is_valid(self):
        self.assertEqual(rm.problems(definitions(), items()), [])
        self.assertEqual(rm.problems(None, [item(1, "done")]), [])

    def test_v1_an_unknown_milestone_id(self):
        its = items()
        its[3]["milestones"] = ["drag"]
        self.assertEqual(rm.problems(definitions(), its), ["milestones: F-004 names the milestone 'drag', which is not defined"])

    def test_v2_a_headline_item_that_is_not_a_member(self):
        its = items()
        its[2]["milestones"] = ["wake"]
        d = definitions()
        d["milestones"][1]["headline"] = ["F-003", "F-001"]
        self.assertEqual(rm.problems(d, its), ["milestones: the headline item F-003 of 'lift' is not a member of it"])

    def test_v3_a_milestone_without_a_headline_item(self):
        d = definitions()
        d["milestones"][0]["headline"] = []
        self.assertEqual(rm.problems(d, items()), ["milestones: 'wake' has no headline item"])

    def test_v4_a_milestone_without_a_member(self):
        its = [dict(it) for it in items()]
        for it in its:
            if "milestones" in it:
                it["milestones"] = [m for m in it["milestones"] if m != "wake"] or None
                if it["milestones"] is None:
                    del it["milestones"]
        got = rm.problems(definitions(), its)
        self.assertIn("milestones: 'wake' has no member", got)

    def test_v5_a_headline_id_that_is_not_an_item(self):
        d = definitions()
        d["milestones"][0]["headline"] = ["F-001", "F-099"]
        self.assertEqual(rm.problems(d, items()), ["milestones: the headline item F-099 of 'wake' is not an item"])

    def test_v6_a_malformed_definitions_file(self):
        for change, want in (
                (lambda d: d["milestones"][0].pop("reference"), "'wake': missing key ['reference']"),
                (lambda d: d["milestones"][0].update(colour="red"), "'wake': unknown key ['colour']"),
                (lambda d: d["milestones"][1].update(id="wake"), "'wake' is defined twice"),
                (lambda d: d["milestones"][1].update(id="Lift 2"), "'Lift 2' is not a milestone id"),
                (lambda d: d["milestones"][0].update(reference="  "), "'wake': reference must be a non-empty string"),
                (lambda d: d["milestones"][0].update(cases="a.rs"), "'wake': cases must be a list of strings"),
                (lambda d: d["milestones"][0].update(headline="F-001"), "'wake': headline must be a list of item ids"),
                (lambda d: d["milestones"][0].update(page="milestone.md"), "'wake': page must be a path under docs/"),
                (lambda d: d.update(milestones={}), "the definitions must be {\"milestones\": [...]}"),
                (lambda d: d.update(version=1), "the definitions must be {\"milestones\": [...]}")):
            d = definitions()
            change(d)
            got = rm.problems(d, items())
            self.assertTrue(line_of(got, "milestones: " + want), (want, got))

    def test_v7_the_key_without_a_definitions_file(self):
        self.assertEqual(rm.problems(None, items()),
                         ["milestones: 3 item(s) have the key milestones and docs/milestones.json does not exist (first F-001)"])


class Figures(unittest.TestCase):
    """A3 and A4."""

    def test_counts_and_per_cent_with_a_partly_done_item_as_one_half(self):
        its = items()
        self.assertEqual(rm.counts(its), (2, 2, 2, 50))  # (2 + 0.5 * 2) / 6
        by = rm.members(definitions(), its)
        self.assertEqual([i["id"] for i in by["wake"]], ["F-001", "F-002"])
        self.assertEqual(rm.counts(by["wake"]), (1, 0, 1, 50))
        self.assertEqual(rm.counts(by["lift"]), (1, 1, 0, 75))
        self.assertEqual(rm.counts([item(1, "done"), item(2, "partial"), item(3, "partial")])[3], 67)  # 2 of 3
        self.assertEqual(rm.counts([item(n, "done") for n in range(1, 386)] + [item(n, "partial") for n in range(386, 679)]
                                   + [item(n, "todo") for n in range(679, 772)]), (385, 293, 93, 69))  # the overview's 69

    def test_nine_done_and_a_partial_headline_is_95_per_cent_and_not_met(self):
        its = [item(n, "done", ["wake"]) for n in range(1, 10)] + [item(10, "partial", ["wake"], gap="torque 38 % low")]
        d = {"milestones": [dict(definitions()["milestones"][0], headline=["F-010"])]}
        self.assertEqual(rm.problems(d, its), [])
        self.assertEqual(rm.counts(its), (9, 1, 0, 95))
        self.assertEqual(rm.milestone_word([its[9]]), "not met")
        text = rm.block(d, its)
        self.assertIn("| Wake of a cylinder | 10 | 9 | 1 | 0 | 95% | not met |", text)
        self.assertIn("  - F-010, Item 10: partly met. Gap: torque 38 % low", text)
        self.assertNotIn("| met |", text)

    def test_the_words_come_from_the_headline_items_alone(self):
        done, part, todo = item(1, "done"), item(2, "partial", gap="g"), item(3, "todo")
        self.assertEqual([rm.headline_word(i) for i in (done, part, todo)], ["met", "partly met", "not started"])
        self.assertEqual(rm.milestone_word([done, done]), "met")
        self.assertEqual(rm.milestone_word([todo, todo]), "not started")
        for mixed in ([done, part], [done, todo], [part], [part, todo]):
            self.assertEqual(rm.milestone_word(mixed), "not met")

    def test_the_block_has_the_whole_roadmap_and_each_milestone(self):
        text = rm.block(definitions(), items())
        self.assertTrue(text.startswith("### Simulation milestones\n\n"))
        self.assertIn("| Whole roadmap | 6 | 2 | 2 | 2 | 50% | not a milestone |\n"
                      "| Wake of a cylinder | 2 | 1 | 0 | 1 | 50% | met |\n"
                      "| Lift of an aerofoil | 2 | 1 | 1 | 0 | 75% | not met |\n", text)
        self.assertIn("- **Wake of a cylinder** (`wake`): Strouhal number against the reference. Cases: "
                      "`crates/x/tests/cylinder.rs`. Reference: A paper, table 1.\n  - F-001, Item 1: met.\n", text)
        self.assertIn("  - F-003, Item 3: partly met. Gap: the stall angle misses by 2 degrees\n", text + "\n")


class Command(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = self.tmp.name
        os.makedirs(os.path.join(self.root, "docs", "adr"))
        self.write_items(items())
        self.write(rr.PAGE, HEAD + rr.render_items(items()))
        self.write(rm.OVERVIEW, OVERVIEW)
        self.write(rm.DEFS, json.dumps(definitions(), indent=2) + "\n")

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, text):
        with open(os.path.join(self.root, rel), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)

    def write_items(self, its):
        self.write(rr.JSON, json.dumps(its, indent=2, ensure_ascii=False) + "\n")

    def read(self, rel):
        with open(os.path.join(self.root, rel), "rb") as fh:
            return fh.read().decode("utf-8")

    def run_main(self, *args):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = rm.main(["--root", self.root, *args])
        return code, buf.getvalue()

    def plain(self):
        """The folder with no key and no definitions file."""
        self.write_items([{k: v for k, v in it.items() if k != "milestones"} for it in items()])
        os.remove(os.path.join(self.root, rm.DEFS))

    def test_each_validation_problem_fails_the_check(self):
        its = items()
        its[3]["milestones"] = ["drag"]
        self.write_items(its)
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("milestones: F-004 names the milestone 'drag', which is not defined", out)
        self.write_items(items())
        d = definitions()
        d["milestones"][0]["headline"] = ["F-004"]
        self.write(rm.DEFS, json.dumps(d))
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("milestones: the headline item F-004 of 'wake' is not a member of it", out)
        self.write(rm.DEFS, "{not json")
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("milestones: docs/milestones.json is not JSON", out)
        os.remove(os.path.join(self.root, rm.DEFS))
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("docs/milestones.json does not exist", out)
        self.assertEqual(self.run_main()[0], 1)  # and nothing is written on a problem
        self.assertEqual(self.read(rm.OVERVIEW), OVERVIEW)

    def test_install_write_and_check_follow_the_roadmap_and_leave_the_other_block(self):
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("has no milestones block: run python scripts/roadmap_milestones.py --install", out)
        self.assertEqual(self.run_main()[0], 1)
        self.assertEqual(self.read(rm.OVERVIEW), OVERVIEW)
        self.assertEqual(self.run_main("--install")[0], 0)
        page = self.read(rm.OVERVIEW)
        want = (REPORT_BLOCK + "\n\n" + rm.BEGIN + "\n" + rm.block(definitions(), items()) + "\n" + rm.END
                + "\n\n## What works today\n")
        self.assertIn(want, page)
        self.assertEqual(page.replace("\n\n" + rm.BEGIN + "\n" + rm.block(definitions(), items()) + "\n" + rm.END, ""), OVERVIEW)
        self.assertEqual(self.run_main("--check")[0], 0)
        self.assertEqual(self.run_main("--install")[0], 0)  # once only
        self.assertEqual(self.read(rm.OVERVIEW), page)
        its = items()
        its[1]["status"] = "done"
        self.write_items(its)
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("docs/roadmap-overview.md: the milestones block is not current", out)
        self.assertEqual(self.read(rm.OVERVIEW), page)
        self.assertEqual(self.run_main()[0], 0)
        self.assertIn("| Wake of a cylinder | 2 | 2 | 0 | 0 | 100% | met |", self.read(rm.OVERVIEW))
        self.assertIn(REPORT_BLOCK + "\n\n" + rm.BEGIN, self.read(rm.OVERVIEW))
        self.assertEqual(self.run_main("--check")[0], 0)

    def test_with_nothing_defined_nothing_is_asked_and_nothing_is_written(self):
        self.plain()
        before = {rel: self.read(rel) for rel in (rr.JSON, rr.PAGE, rm.OVERVIEW)}
        self.assertEqual(self.run_main("--check")[0], 0)
        self.assertEqual(self.run_main()[0], 0)
        self.assertEqual({rel: self.read(rel) for rel in before}, before)
        self.assertFalse(os.path.exists(os.path.join(self.root, rm.DEFS)))
        self.write(rm.OVERVIEW, OVERVIEW + "\n" + rm.BEGIN + "\nold\n" + rm.END + "\n")
        code, out = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn("carries the milestones block and docs/milestones.json does not exist", out)

    def test_apply_sets_the_keys_from_a_mapping_and_touches_nothing_else(self):
        self.plain()
        self.write("docs/adr/defs.json", json.dumps(definitions(), indent=2) + "\n")
        mapping = ("# item\tmilestone\treason\n\nF-001\twake\tM1 headline\nF-002\twake\tM2 the solver\n"
                   "F-003\tlift\tM1 headline\nF-001\tlift\tM2 the solver\n")
        self.write("docs/adr/map.tsv", mapping)
        before = self.read(rr.JSON)
        code, out = self.run_main("--apply", "docs/adr/map.tsv", "--definitions", "docs/adr/defs.json", "--install")
        self.assertEqual(code, 0, out)
        got = json.loads(self.read(rr.JSON))
        self.assertEqual(got, items())  # F-001 in the order of the definitions, the key last
        self.assertEqual(list(got[0])[-1], "milestones")
        self.assertEqual(self.read(rm.DEFS), self.read("docs/adr/defs.json"))
        self.assertEqual(self.run_main("--check")[0], 0)
        after = self.read(rr.JSON)
        cut = lambda text, k: text[text.index(f'"id": "{k}"'):].split("\n  },")[0]
        for k in ("F-004", "F-005", "F-006"):
            self.assertEqual(cut(after, k), cut(before, k))
        self.assertNotEqual(cut(after, "F-002"), cut(before, "F-002"))  # the control: the key is seen
        self.assertEqual(self.run_main("--apply", "docs/adr/map.tsv", "--definitions", "docs/adr/defs.json")[0], 0)
        self.assertEqual(self.read(rr.JSON), after)  # a second time changes nothing
        # a mapping that names one milestone replaces that milestone's members and no other's
        self.write("docs/adr/map2.tsv", "F-001\twake\tM1 headline\nF-004\twake\tM2 the mesh\n")
        self.assertEqual(self.run_main("--apply", "docs/adr/map2.tsv")[0], 0)
        got = {i["id"]: i.get("milestones") for i in json.loads(self.read(rr.JSON))}
        self.assertEqual(got, {"F-001": ["wake", "lift"], "F-002": None, "F-003": ["lift"], "F-004": ["wake"], "F-005": None,
                               "F-006": None})

    def test_apply_refuses_a_bad_mapping_and_a_file_it_would_reformat(self):
        before = self.read(rr.JSON)
        for text, want in (("F-099\twake\tM2 x\n", "F-099 is not an item"), ("F-004\tdrag\tM2 x\n", "'drag' is not defined"),
                           ("F-004\twake\n", "line 1 is not <item id> tab <milestone id> tab <reason>"),
                           ("F-004\twake\t \n", "line 1 is not <item id> tab <milestone id> tab <reason>"),
                           ("F-004\twake\tM2 x\nF-004\twake\tM2 y\n", "F-004 and 'wake' occur twice"),
                           ("F-004\twake\tM2 x\n", "the headline item F-001 of 'wake' is not a member of it")):
            self.write("docs/adr/map.tsv", text)
            code, out = self.run_main("--apply", "docs/adr/map.tsv")
            self.assertEqual(code, 1, text)
            self.assertIn(want, out)
            self.assertEqual(self.read(rr.JSON), before)
        self.write(rr.JSON, json.dumps(items()))
        self.write("docs/adr/map.tsv", "F-001\twake\tM1 headline\nF-004\twake\tM2 x\n")
        code, out = self.run_main("--apply", "docs/adr/map.tsv")
        self.assertEqual(code, 1)
        self.assertIn("docs/roadmap.json is not laid out as this script writes it", out)
        self.assertEqual(self.read(rr.JSON), json.dumps(items()))


