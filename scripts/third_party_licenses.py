"""Writes THIRD_PARTY_LICENSES.md: every registry package in Cargo.lock with its version and the licence its manifest
declares (from `cargo metadata --offline --locked`), plus the notices that need more than an SPDX id.

Usage, from the repository root:
    python scripts/third_party_licenses.py          rewrite THIRD_PARTY_LICENSES.md
    python scripts/third_party_licenses.py --check  exit 1 if the committed file differs from a fresh generation
Standard library only.
"""
import collections
import json
import subprocess
import sys

OUT = "THIRD_PARTY_LICENSES.md"

HEADER = """# Third-party licences

This file lists the third-party Rust packages that rcfd depends on: every registry package in `Cargo.lock`, on every target,
including optional, platform-specific and test-only packages, so a given binary contains a subset. The licence column is the
`license` field each package declares in its manifest, as reported by `cargo metadata`; it is not a reading of the packages'
licence files. rcfd vendors no dependency source: cargo downloads each package from crates.io under its own licence.

Generated by `python scripts/third_party_licenses.py` (run it again after a change to `Cargo.lock`; `--check` reports a stale
file). For rcfd's own licence see `LICENSE` and `NOTICE`; for data, see `NOTICE` and
`validation-data/manifest.json`.

## Notices that need more than the licence id

A binary distribution of rcfd must carry the licence texts and notices of the packages it contains. These need particular care:

* `epaint` (through `egui`, only in the desktop app `rcfd-gui`): declares `(MIT OR Apache-2.0) AND OFL-1.1 AND
  LicenseRef-UFL-1.0` because it bundles fonts. The SIL Open Font License 1.1 and the Ubuntu Font Licence 1.0 texts must ship
  with any binary that embeds those fonts. Which font carries which licence is recorded in the `epaint` package (not checked
  here: UNVERIFIED).
* Unicode-3.0 (`unicode-ident` and the `icu_*`, `zerovec`, `yoke`, `tinystr`, `litemap`, `writeable`, `zerofrom` family): the
  Unicode licence notice must accompany copies of the data.
* CDLA-Permissive-2.0 (`webpki-roots`, a bundle of certificate-authority data): the licence text must accompany the data.
* `ring`: declares `Apache-2.0 AND ISC`. Its licence file may carry further notices for code derived from other projects; the
  full set was not read here (UNVERIFIED) and must be checked before a binary release.
* BSD-2-Clause, BSD-3-Clause, ISC, Zlib, BSL-1.0, MIT and CC0-1.0 packages: keep their copyright and licence texts in binary
  distributions (CC0 asks for nothing but is listed for completeness).
* Apache-2.0 packages: ship any `NOTICE` file a package provides (which packages have one was not checked: UNVERIFIED).
* Packages with an `OR` licence (for example `r-efi`, which also offers LGPL-2.1-or-later) are used under their permissive
  option.

"""


def generate():
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--offline", "--locked", "--format-version", "1"],
        capture_output=True, check=True).stdout)
    pkgs = sorted(
        {(p["name"], p["version"], p.get("license") or "NONE declared (see the package's licence file)")
         for p in meta["packages"] if (p.get("source") or "").startswith("registry+")},
        key=lambda t: (t[0], [int(x) if x.isdigit() else x for x in t[1].replace("+", ".").replace("-", ".").split(".")]))
    assert pkgs, "no registry packages found"
    counts = collections.Counter(lic for _, _, lic in pkgs)
    lines = [HEADER, f"## Licence summary ({len(pkgs)} packages)\n\n", "| Licence (as declared) | Packages |\n|---|---|\n"]
    lines += [f"| `{lic}` | {n} |\n" for lic, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    lines += ["\n## Packages\n\n", "| Package | Version | Licence (as declared) |\n|---|---|---|\n"]
    lines += [f"| {n} | {v} | `{lic}` |\n" for n, v, lic in pkgs]
    return "".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        try:
            current = open(OUT, encoding="utf-8").read()
        except OSError:
            current = None
        if current != text:
            print(f"{OUT} is stale: run python scripts/third_party_licenses.py")
            return 1
        print(f"{OUT} is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
