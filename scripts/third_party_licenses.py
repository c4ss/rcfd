"""Writes THIRD_PARTY_LICENSES.md: every registry package in Cargo.lock with its version and the licence its manifest
declares (from `cargo metadata --offline --locked`), every npm package in the lock file of the Electron Studio
(apps/studio-web/package-lock.json, ADR 0801) with the licence its lock entry records, plus the notices that need more
than an SPDX id.

Usage, from the repository root:
    python scripts/third_party_licenses.py          rewrite THIRD_PARTY_LICENSES.md
    python scripts/third_party_licenses.py --check  exit 1 if the committed file differs from a fresh generation
Standard library only.
"""
import collections
import json
import subprocess
import sys

OUT = "THIRD_PARTY_LICENSES.md"
NPM_APP = "apps/studio-web"

HEADER = """# Third-party licences

This file lists the third-party Rust packages that rcfd depends on: every registry package in `Cargo.lock`, on every target,
including optional, platform-specific and test-only packages, so a given binary contains a subset. The licence column is the
`license` field each package declares in its manifest, as reported by `cargo metadata`; it is not a reading of the packages'
licence files. rcfd vendors no dependency source: cargo downloads each package from crates.io under its own licence.

It also lists the npm packages of the Electron Studio (`apps/studio-web/`, outside the Cargo workspace, ADR 0801): every
package in `apps/studio-web/package-lock.json`, including development-only and platform-specific optional ones. Their licence
column is the `license` field npm records in the lock file from each package's manifest. npm downloads each package from the
npm registry under its own licence; none is vendored. The design prototype `apps/studio-prototype/` and the measurement shell
`bench/electron/` are not products and are not listed.

Generated by `python scripts/third_party_licenses.py` (run it again after a change to `Cargo.lock` or to
`apps/studio-web/package-lock.json`; `--check` reports a stale file). For rcfd's own licence see `LICENSE` and `NOTICE`; for
data, see `NOTICE` and `validation-data/manifest.json`.

## Notices that need more than the licence id

A binary distribution of rcfd must carry the licence texts and notices of the packages it contains. These need particular care:

* `epaint_default_fonts` (through `egui` 0.36, in the two desktop apps `rcfd-studio` and `rcfd-gui`): bundles egui's default
  fonts and declares `(MIT OR Apache-2.0) AND OFL-1.1 AND Ubuntu-font-1.0`. The SIL Open Font License 1.1 and the Ubuntu Font
  Licence 1.0 texts must ship with any binary that embeds those fonts. Which font carries which licence is recorded in the
  package (not checked here: UNVERIFIED).
* Unicode-3.0 (`unicode-ident` and the `icu_*`, `zerovec`, `yoke`, `tinystr`, `litemap`, `writeable`, `zerofrom` family): the
  Unicode licence notice must accompany copies of the data.
* CDLA-Permissive-2.0 (`webpki-roots`, a bundle of certificate-authority data): the licence text must accompany the data.
* `ring`: declares `Apache-2.0 AND ISC`. Its licence file may carry further notices for code derived from other projects; the
  full set was not read here (UNVERIFIED) and must be checked before a binary release.
* BSD-2-Clause, BSD-3-Clause, ISC, Zlib, BSL-1.0, MIT and CC0-1.0 packages: keep their copyright and licence texts in binary
  distributions (CC0 asks for nothing but is listed for completeness).
* Apache-2.0 packages: ship any `NOTICE` file a package provides (which packages have one was not checked: UNVERIFIED).
* Packages with an `OR` licence (for example `r-efi`, which also offers LGPL-2.1-or-later) are used under their permissive
  option.

For the npm packages of the Electron Studio (`apps/studio-web/`):

* `electron` (MIT) downloads the Electron binary on first use. The binary bundles Chromium, Node.js and their own
  dependencies under many licences; it carries `LICENSE` and `LICENSES.chromium.html`, and both must ship with any packaged
  Studio (F-820). They were not read here (UNVERIFIED).
* `@fontsource/archivo` (OFL-1.1): the Archivo font files are copied into the renderer build. The SIL Open Font License 1.1
  text (the package's `LICENSE`) must ship with any distribution that contains them; the fonts may not be sold by themselves.
* MPL-2.0 (`lightningcss` and its platform packages, through `vite`): build tools only; no MPL-2.0 code is copied into the
  built app. MPL-2.0 is compatible with AGPL-3.0 (MPL-2.0 section 3.3).
* Apache-2.0 (`react-aria-components`, `react-aria`, `react-stately`, `@internationalized/*`, `@react-types/shared`,
  `@swc/helpers`; `typescript` and its platform packages as build tools): keep the licence text and any `NOTICE` file in a
  distribution. Of the installed packages (Windows x64) only `typescript` ships a `NOTICE.txt`, and it is a build tool.
* MIT, ISC, BSD-3-Clause, 0BSD and BlueOak-1.0.0 packages: keep their copyright and licence texts in distributions.

"""


def generate():
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--offline", "--locked", "--format-version", "1"],
        capture_output=True, check=True).stdout)
    pkgs = sorted(
        {(p["name"], p["version"], p.get("license") or "NONE declared (see the package's licence file)")
         for p in meta["packages"] if (p.get("source") or "").startswith("registry+")},
        key=lambda t: (t[0], [int(x) if x.isdigit() else x for x in t[1].replace("+", ".").replace("-", ".").split(".")]))
    assert pkgs, "no registry packages found"
    counts = collections.Counter(lic for _, _, lic in pkgs)
    lines = [HEADER, f"## Licence summary ({len(pkgs)} packages)\n\n", "| Licence (as declared) | Packages |\n|---|---|\n"]
    lines += [f"| `{lic}` | {n} |\n" for lic, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    lines += ["\n## Packages\n\n", "| Package | Version | Licence (as declared) |\n|---|---|---|\n"]
    lines += [f"| {n} | {v} | `{lic}` |\n" for n, v, lic in pkgs]
    lines += npm_section()
    return "".join(lines)


def npm_section():
    """The npm packages of apps/studio-web: the direct ones from its package.json, all of them from package-lock.json."""
    with open(f"{NPM_APP}/package.json", encoding="utf-8") as f:
        manifest = json.load(f)
    with open(f"{NPM_APP}/package-lock.json", encoding="utf-8") as f:
        lock = json.load(f)
    assert lock.get("lockfileVersion", 0) >= 2, f"{NPM_APP}/package-lock.json must be lockfileVersion 2 or 3"
    direct = {n: "`dependencies`" for n in manifest.get("dependencies", {})}
    direct.update({n: "`devDependencies`" for n in manifest.get("devDependencies", {})})
    pkgs = []
    for path, p in lock["packages"].items():
        if not path:
            continue
        name = path.rsplit("node_modules/", 1)[1]
        kind = "development" if p.get("dev") else "runtime"
        if p.get("optional"):
            kind += ", optional" + (f" ({', '.join(p['os'])})" if p.get("os") else "")
        pkgs.append((name, p["version"], p.get("license") or "NONE recorded (see the package's licence file)", kind))
    pkgs.sort(key=lambda t: (t[0], t[1]))
    top = {path.split("node_modules/", 1)[1]: p for path, p in lock["packages"].items() if path.count("node_modules/") == 1}
    for n in direct:
        assert n in top, f"{n} is in {NPM_APP}/package.json but not in its lock file"
    lines = ["\n## npm packages of the Electron Studio (apps/studio-web)\n\n",
             "### Direct dependencies\n\n",
             "Pinned to exact versions in `apps/studio-web/package.json` and justified in ADR 0801.\n\n",
             "| Package | Version | Licence (as recorded) | Declared in package.json |\n|---|---|---|---|\n"]
    lines += [f"| {n} | {top[n]['version']} | `{top[n].get('license')}` | {k} |\n"
              for n, k in sorted(direct.items(), key=lambda kv: (kv[1] != "`dependencies`", kv[0]))]
    counts = collections.Counter(lic for _, _, lic, _ in pkgs)
    lines += [f"\n### Licence summary ({len(pkgs)} packages in the lock file)\n\n",
              "| Licence (as recorded) | Packages |\n|---|---|\n"]
    lines += [f"| `{lic}` | {n} |\n" for lic, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    lines += ["\n### Packages\n\n",
              "Development packages are build and test tools; the built app contains only the runtime packages and the "
              "Electron binary. Optional packages are platform-specific and installed only on the platform named.\n\n",
              "| Package | Version | Licence (as recorded) | Kind |\n|---|---|---|---|\n"]
    lines += [f"| {n} | {v} | `{lic}` | {k} |\n" for n, v, lic, k in pkgs]
    return lines


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        try:
            current = open(OUT, encoding="utf-8").read()
        except OSError:
            current = None
        if current != text:
            print(f"{OUT} is stale: run python scripts/third_party_licenses.py")
            return 1
        print(f"{OUT} is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
